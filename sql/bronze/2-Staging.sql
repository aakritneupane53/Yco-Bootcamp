USE DATABASE RETAIL_DB;
SELECT CURRENT_DATABASE();

SHOW SCHEMAS;

USE SCHEMA STG;
SELECT CURRENT_SCHEMA();

CREATE FILE FORMAT IF NOT EXISTS RETAIL_DB.STG.FF_RETAIL_CSV
    TYPE = CSV
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    TRIM_SPACE = FALSE
    EMPTY_FIELD_AS_NULL = FALSE
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE
    SKIP_BLANK_LINES = FALSE
    COMMENT = 'CSV source format; preserve empty strings and source values for STG.';

CREATE STAGE IF NOT EXISTS RETAIL_DB.STG.STG_RETAIL_SOURCE
    FILE_FORMAT = (FORMAT_NAME = RETAIL_DB.STG.FF_RETAIL_CSV)
    DIRECTORY = (ENABLE = TRUE)
    COMMENT = 'Internal landing stage for retail source CSV files.';

-- 1. Item master: one source row per item in each daily snapshot file.
CREATE TABLE IF NOT EXISTS STG_ITEM_MASTER (
    ITEM_ID             VARCHAR,
    ITEM_NAME           VARCHAR,
    SUBCATEGORY_ID      VARCHAR,
    SUBCATEGORY_NAME    VARCHAR,
    CATEGORY_ID         VARCHAR,
    CATEGORY_NAME       VARCHAR,
    BRAND_ID            VARCHAR,
    BRAND_NAME          VARCHAR,
    UNIT_OF_MEASURE     VARCHAR,
    ACTIVE_FLG          VARCHAR,

    SRC_FILE_NM         VARCHAR(1000),
    ROW_NUM             NUMBER(38,0),
    INGEST_TS           TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
    BATCH_ID            VARCHAR(100)
);

-- 2. Store master: one source row per store in each weekly snapshot file.
CREATE TABLE IF NOT EXISTS STG_STORE_MASTER (
    STORE_ID            VARCHAR,
    STORE_NAME          VARCHAR,
    REGION_ID           VARCHAR,
    REGION_NAME         VARCHAR,
    COUNTRY_ID          VARCHAR,
    COUNTRY_NAME        VARCHAR,
    CITY                VARCHAR,
    STORE_TYPE          VARCHAR,
    ACTIVE_FLG          VARCHAR,

    SRC_FILE_NM         VARCHAR(1000),
    ROW_NUM             NUMBER(38,0),
    INGEST_TS           TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
    BATCH_ID            VARCHAR(100)
);

-- 3. POS sales: one source row per transaction line.
CREATE TABLE IF NOT EXISTS STG_POS_SALES (
    TRANSACTION_ID      VARCHAR,
    LINE_NUMBER         VARCHAR,
    SALE_DATETIME       VARCHAR,
    BUSINESS_DATE       VARCHAR,
    STORE_ID            VARCHAR,
    ITEM_ID             VARCHAR,
    CUSTOMER_ID         VARCHAR,
    SOLD_QTY            VARCHAR,
    SELLING_PRICE_AMT   VARCHAR,
    DISCOUNT_AMT        VARCHAR,
    SALES_AMT           VARCHAR,
    COST_AMT            VARCHAR,

    SRC_FILE_NM         VARCHAR(1000),
    ROW_NUM             NUMBER(38,0),
    INGEST_TS           TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
    BATCH_ID            VARCHAR(100)
);

-- 4. Inventory snapshot: one source row per item, store and business date.
CREATE TABLE IF NOT EXISTS STG_INVENTORY_SNAPSHOT (
    BUSINESS_DATE       VARCHAR,
    ITEM_ID             VARCHAR,
    STORE_ID            VARCHAR,
    ON_HAND_QTY         VARCHAR,
    AVAILABLE_QTY       VARCHAR,
    RESERVED_QTY        VARCHAR,
    INVENTORY_VALUE_AMT VARCHAR,

    SRC_FILE_NM         VARCHAR(1000),
    ROW_NUM             NUMBER(38,0),
    INGEST_TS           TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
    BATCH_ID            VARCHAR(100)
);

-- 5. Customer master: one source row per customer in the reference file.
CREATE TABLE IF NOT EXISTS STG_CUSTOMER_MASTER (
    CUSTOMER_ID         VARCHAR,
    CUSTOMER_NAME       VARCHAR,
    CITY                VARCHAR,
    LOYALTY_TIER        VARCHAR,
    REGISTRATION_DATE   VARCHAR,
    ACTIVE_FLG          VARCHAR,

    SRC_FILE_NM         VARCHAR(1000),
    ROW_NUM             NUMBER(38,0),
    INGEST_TS           TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
    BATCH_ID            VARCHAR(100)
);

-- 6. Price snapshot: one source row per item, store and business date.
CREATE TABLE IF NOT EXISTS STG_PRICE_SNAPSHOT (
    BUSINESS_DATE       VARCHAR,
    ITEM_ID             VARCHAR,
    STORE_ID            VARCHAR,
    SELLING_PRICE_AMT   VARCHAR,
    UNIT_COST_AMT       VARCHAR,

    SRC_FILE_NM         VARCHAR(1000),
    ROW_NUM             NUMBER(38,0),
    INGEST_TS           TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
    BATCH_ID            VARCHAR(100)
);
-- Logs of alread written file 
CREATE TABLE IF NOT EXISTS STG_INGESTION_LOG (
    FILE_NAME       VARCHAR(500) NOT NULL,
    TARGET_TABLE    VARCHAR(200) NOT NULL,
    LOAD_STATUS     VARCHAR(20) NOT NULL,
    LOAD_TS         TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    ERROR_MESSAGE   VARCHAR(2000)
);
