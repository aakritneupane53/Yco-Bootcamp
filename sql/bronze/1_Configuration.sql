CREATE WAREHOUSE IF NOT EXISTS RETAIL_WH
WITH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE RETAIL_WH;

SELECT CURRENT_WAREHOUSE();


CREATE DATABASE IF NOT EXISTS RETAIL_DB;

CREATE SCHEMA IF NOT EXISTS RETAIL_DB.STG;
CREATE SCHEMA IF NOT EXISTS RETAIL_DB.TMP;
CREATE SCHEMA IF NOT EXISTS RETAIL_DB.TGT;
CREATE SCHEMA IF NOT EXISTS RETAIL_DB.MART;


-- Fetching the user details
SELECT
    CURRENT_USER()      AS USER_NAME,
    CURRENT_ROLE()      AS ROLE_NAME,
    CURRENT_DATABASE()  AS DATABASE_NAME,
    CURRENT_SCHEMA()    AS SCHEMA_NAME,
    CURRENT_WAREHOUSE() AS WAREHOUSE_NAME,
    CURRENT_ACCOUNT()   AS ACCOUNT_IDENTIFIER;


SELECT
    CURRENT_ACCOUNT() AS ACCOUNT_LOCATOR,
    CURRENT_ROLE() AS ROLE_NAME;

