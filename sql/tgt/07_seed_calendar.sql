-- Seed all five calendar levels from the dates present in the Silver facts.
-- A contiguous range is generated, including dates without a transaction.
CREATE OR REPLACE TEMP TABLE RETAIL_DB.TGT.TMP_CALENDAR_DATES AS
WITH ALL_SOURCE_DATES AS (
    SELECT BUSINESS_DATE AS SOURCE_DT FROM RETAIL_DB.TMP.SILVER_POS_SALES
    UNION ALL
    SELECT BUSINESS_DATE FROM RETAIL_DB.TMP.SILVER_INVENTORY_SNAPSHOT
    UNION ALL
    SELECT BUSINESS_DATE FROM RETAIL_DB.TMP.SILVER_PRICE_SNAPSHOT
),
BOUNDS AS (
    SELECT MIN(SOURCE_DT) AS MIN_DT, MAX(SOURCE_DT) AS MAX_DT
    FROM ALL_SOURCE_DATES
)
SELECT DATEADD(DAY, N.DAY_OFFSET, B.MIN_DT)::DATE AS DAY_DT
FROM BOUNDS B
CROSS JOIN (
    -- SEQ4 values are not guaranteed gap-free. ROW_NUMBER provides a
    -- contiguous sequence so every calendar date is generated exactly once.
    SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS DAY_OFFSET
    FROM TABLE(GENERATOR(ROWCOUNT => 36600))
) N
WHERE B.MIN_DT IS NOT NULL
  AND DATEADD(DAY, N.DAY_OFFSET, B.MIN_DT)::DATE <= B.MAX_DT;

-- Calendar years must include ISO years, which can differ at year boundaries.
MERGE INTO RETAIL_DB.TGT.DIM_YEAR T
USING (
    SELECT DISTINCT YEAR(DAY_DT) AS YEAR_ID FROM RETAIL_DB.TGT.TMP_CALENDAR_DATES
    UNION
    SELECT DISTINCT YEAROFWEEKISO(DAY_DT) AS YEAR_ID FROM RETAIL_DB.TGT.TMP_CALENDAR_DATES
) S
ON T.YEAR_ID = S.YEAR_ID
WHEN MATCHED THEN UPDATE SET T.UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (YEAR_ID, INSERT_TS, UPDATE_TS)
VALUES (S.YEAR_ID, CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP());

MERGE INTO RETAIL_DB.TGT.DIM_QUARTER T
USING (
    SELECT DISTINCT
        (TO_VARCHAR(YEAR(D.DAY_DT)) || 'Q' || TO_VARCHAR(QUARTER(D.DAY_DT))) AS QUARTER_ID,
        QUARTER(D.DAY_DT)::NUMBER(1,0) AS QUARTER_NBR,
        Y.YEAR_KY
    FROM RETAIL_DB.TGT.TMP_CALENDAR_DATES D
    JOIN RETAIL_DB.TGT.DIM_YEAR Y ON Y.YEAR_ID = YEAR(D.DAY_DT)
) S
ON T.QUARTER_ID = S.QUARTER_ID
WHEN MATCHED THEN UPDATE SET
    T.QUARTER_NBR = S.QUARTER_NBR, T.YEAR_KY = S.YEAR_KY,
    T.UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (QUARTER_ID, QUARTER_NBR, YEAR_KY, INSERT_TS, UPDATE_TS)
VALUES (S.QUARTER_ID, S.QUARTER_NBR, S.YEAR_KY, CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP());

MERGE INTO RETAIL_DB.TGT.DIM_MONTH T
USING (
    SELECT DISTINCT
        (YEAR(D.DAY_DT) * 100 + MONTH(D.DAY_DT))::NUMBER(6,0) AS MONTH_ID,
        MONTHNAME(D.DAY_DT) AS MONTH_NM,
        MONTH(D.DAY_DT)::NUMBER(2,0) AS MONTH_NBR,
        Q.QUARTER_KY
    FROM RETAIL_DB.TGT.TMP_CALENDAR_DATES D
    JOIN RETAIL_DB.TGT.DIM_QUARTER Q
      ON Q.QUARTER_ID = (TO_VARCHAR(YEAR(D.DAY_DT)) || 'Q' || TO_VARCHAR(QUARTER(D.DAY_DT)))
) S
ON T.MONTH_ID = S.MONTH_ID
WHEN MATCHED THEN UPDATE SET
    T.MONTH_NM = S.MONTH_NM, T.MONTH_NBR = S.MONTH_NBR,
    T.QUARTER_KY = S.QUARTER_KY, T.UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (MONTH_ID, MONTH_NM, MONTH_NBR, QUARTER_KY, INSERT_TS, UPDATE_TS)
VALUES (S.MONTH_ID, S.MONTH_NM, S.MONTH_NBR, S.QUARTER_KY, CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP());

MERGE INTO RETAIL_DB.TGT.DIM_WEEK T
USING (
    SELECT DISTINCT
        (YEAROFWEEKISO(D.DAY_DT) * 100 + WEEKISO(D.DAY_DT))::NUMBER(6,0) AS WEEK_ID,
        WEEKISO(D.DAY_DT)::NUMBER(2,0) AS WEEK_NBR,
        DATEADD(DAY, 1 - DAYOFWEEKISO(D.DAY_DT), D.DAY_DT)::DATE AS WEEK_START_DT,
        DATEADD(DAY, 7 - DAYOFWEEKISO(D.DAY_DT), D.DAY_DT)::DATE AS WEEK_END_DT,
        Y.YEAR_KY AS ISO_YEAR_KY
    FROM RETAIL_DB.TGT.TMP_CALENDAR_DATES D
    JOIN RETAIL_DB.TGT.DIM_YEAR Y ON Y.YEAR_ID = YEAROFWEEKISO(D.DAY_DT)
) S
ON T.WEEK_ID = S.WEEK_ID
WHEN MATCHED THEN UPDATE SET
    T.WEEK_NBR = S.WEEK_NBR, T.WEEK_START_DT = S.WEEK_START_DT,
    T.WEEK_END_DT = S.WEEK_END_DT, T.ISO_YEAR_KY = S.ISO_YEAR_KY,
    T.UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    WEEK_ID, WEEK_NBR, WEEK_START_DT, WEEK_END_DT, ISO_YEAR_KY, INSERT_TS, UPDATE_TS
) VALUES (
    S.WEEK_ID, S.WEEK_NBR, S.WEEK_START_DT, S.WEEK_END_DT, S.ISO_YEAR_KY,
    CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP()
);

MERGE INTO RETAIL_DB.TGT.DIM_DAY T
USING (
    SELECT
        TO_NUMBER(TO_CHAR(D.DAY_DT, 'YYYYMMDD')) AS DAY_ID,
        D.DAY_DT,
        DAYOFWEEKISO(D.DAY_DT)::NUMBER(1,0) AS DAY_OF_WEEK_NBR,
        IFF(DAYOFWEEKISO(D.DAY_DT) IN (6, 7), TRUE, FALSE) AS IS_WEEKEND_FLG,
        M.MONTH_KY,
        W.WEEK_KY
    FROM RETAIL_DB.TGT.TMP_CALENDAR_DATES D
    JOIN RETAIL_DB.TGT.DIM_MONTH M
      ON M.MONTH_ID = YEAR(D.DAY_DT) * 100 + MONTH(D.DAY_DT)
    JOIN RETAIL_DB.TGT.DIM_WEEK W
      ON W.WEEK_ID = YEAROFWEEKISO(D.DAY_DT) * 100 + WEEKISO(D.DAY_DT)
) S
ON T.DAY_ID = S.DAY_ID
WHEN MATCHED THEN UPDATE SET
    T.DAY_DT = S.DAY_DT, T.DAY_OF_WEEK_NBR = S.DAY_OF_WEEK_NBR,
    T.IS_WEEKEND_FLG = S.IS_WEEKEND_FLG, T.MONTH_KY = S.MONTH_KY,
    T.WEEK_KY = S.WEEK_KY, T.UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    DAY_ID, DAY_DT, DAY_OF_WEEK_NBR, IS_WEEKEND_FLG, MONTH_KY, WEEK_KY, INSERT_TS, UPDATE_TS
) VALUES (
    S.DAY_ID, S.DAY_DT, S.DAY_OF_WEEK_NBR, S.IS_WEEKEND_FLG, S.MONTH_KY, S.WEEK_KY,
    CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP()
);
