-- FCT_INVENTORY: one item + store + business date observation.
MERGE INTO RETAIL_DB.TGT.FCT_INVENTORY T
USING (
    SELECT
        I.ITEM_KY, ST.STORE_KY, D.DAY_KY,
        S.ON_HAND_QTY, S.AVAILABLE_QTY, S.RESERVED_QTY, S.INVENTORY_VALUE_AMT,
        S.SRC_SYS_C, S.BATCH_ID
    FROM RETAIL_DB.TMP.SILVER_INVENTORY_SNAPSHOT S
    JOIN RETAIL_DB.TGT.DIM_ITEM I
      ON I.ITEM_ID = S.ITEM_ID AND S.BUSINESS_DATE BETWEEN I.EFF_FROM_DT AND I.EFF_TO_DT
    JOIN RETAIL_DB.TGT.DIM_STORE ST
      ON ST.STORE_ID = S.STORE_ID AND S.BUSINESS_DATE BETWEEN ST.EFF_FROM_DT AND ST.EFF_TO_DT
    JOIN RETAIL_DB.TGT.DIM_DAY D ON D.DAY_DT = S.BUSINESS_DATE
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY I.ITEM_KY, ST.STORE_KY, D.DAY_KY
        ORDER BY S.UPDATE_TS DESC, S.SRC_FILE_NM DESC, S.ROW_NUM DESC
    ) = 1
) S
ON T.ITEM_KY = S.ITEM_KY AND T.STORE_KY = S.STORE_KY AND T.DAY_KY = S.DAY_KY
WHEN MATCHED THEN UPDATE SET
    T.ON_HAND_QTY = S.ON_HAND_QTY, T.AVAILABLE_QTY = S.AVAILABLE_QTY,
    T.RESERVED_QTY = S.RESERVED_QTY, T.INVENTORY_VALUE_AMT = S.INVENTORY_VALUE_AMT,
    T.SRC_SYS_C = S.SRC_SYS_C, T.BATCH_ID = S.BATCH_ID,
    T.UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    ITEM_KY, STORE_KY, DAY_KY, ON_HAND_QTY, AVAILABLE_QTY, RESERVED_QTY,
    INVENTORY_VALUE_AMT, SRC_SYS_C, BATCH_ID, INSERT_TS, UPDATE_TS
) VALUES (
    S.ITEM_KY, S.STORE_KY, S.DAY_KY, S.ON_HAND_QTY, S.AVAILABLE_QTY,
    S.RESERVED_QTY, S.INVENTORY_VALUE_AMT, S.SRC_SYS_C, S.BATCH_ID,
    CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP()
);
