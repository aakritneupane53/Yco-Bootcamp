-- DIM_REGION (SCD1). REGION_ID is scoped by COUNTRY_ID.
MERGE INTO RETAIL_DB.TGT.DIM_REGION T
USING (
    WITH LATEST_STORE AS (
        SELECT COUNTRY_ID, REGION_ID, REGION_NAME, ACTIVE_FLG, SRC_SYS_C,
               BATCH_ID, SNAPSHOT_DT, STORE_ID
        FROM RETAIL_DB.TMP.SILVER_STORE_MASTER
        QUALIFY ROW_NUMBER() OVER (
            PARTITION BY STORE_ID
            ORDER BY SNAPSHOT_DT DESC, UPDATE_TS DESC, SRC_FILE_NM DESC, ROW_NUM DESC
        ) = 1
    ),
    REGION_NAME AS (
        SELECT COUNTRY_ID, REGION_ID, REGION_NAME, SRC_SYS_C, BATCH_ID
        FROM LATEST_STORE
        QUALIFY ROW_NUMBER() OVER (
            PARTITION BY COUNTRY_ID, REGION_ID
            ORDER BY SNAPSHOT_DT DESC, STORE_ID
        ) = 1
    ),
    REGION_STATUS AS (
        SELECT COUNTRY_ID, REGION_ID,
               BOOLOR_AGG(COALESCE(ACTIVE_FLG, FALSE)) AS ACTIVE_FLG
        FROM LATEST_STORE GROUP BY COUNTRY_ID, REGION_ID
    )
    SELECT N.REGION_ID, N.REGION_NAME AS REGION_NM, C.COUNTRY_KY,
           S.ACTIVE_FLG, N.SRC_SYS_C, N.BATCH_ID
    FROM REGION_NAME N
    JOIN REGION_STATUS S
      ON S.COUNTRY_ID = N.COUNTRY_ID AND S.REGION_ID = N.REGION_ID
    JOIN RETAIL_DB.TGT.DIM_COUNTRY C ON C.COUNTRY_ID = N.COUNTRY_ID
) S
ON T.COUNTRY_KY = S.COUNTRY_KY AND T.REGION_ID = S.REGION_ID
WHEN MATCHED THEN UPDATE SET
    T.REGION_NM = S.REGION_NM,
    T.ACTIVE_FLG = S.ACTIVE_FLG,
    T.SRC_SYS_C = S.SRC_SYS_C,
    T.BATCH_ID = S.BATCH_ID,
    T.UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    REGION_ID, REGION_NM, COUNTRY_KY, ACTIVE_FLG, SRC_SYS_C, BATCH_ID, INSERT_TS, UPDATE_TS
) VALUES (
    S.REGION_ID, S.REGION_NM, S.COUNTRY_KY, S.ACTIVE_FLG, S.SRC_SYS_C, S.BATCH_ID,
    CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP()
);
