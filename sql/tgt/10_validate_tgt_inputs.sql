
-- Pre-fact quality gate with diagnostic details.
-- Any non-zero VIOLATION_COUNT stops the DAG.
-- Third column contains examples for unresolved dimension references.

WITH ITEM_VERSION_PROFILE AS (
    SELECT
        ITEM_ID,
        COUNT(*) AS VERSION_COUNT,
        LISTAGG(
            TO_VARCHAR(EFF_FROM_DT) || ' to ' || TO_VARCHAR(EFF_TO_DT) ||
            ' (ACTIVE=' || COALESCE(TO_VARCHAR(ACTIVE_FLG), 'NULL') ||
            ', CURR=' || COALESCE(TO_VARCHAR(CURR_FLG), 'NULL') || ')',
            '; '
        ) WITHIN GROUP (ORDER BY EFF_FROM_DT) AS VERSION_RANGES
    FROM RETAIL_DB.TGT.DIM_ITEM
    GROUP BY ITEM_ID
),

STORE_VERSION_PROFILE AS (
    SELECT
        STORE_ID,
        COUNT(*) AS VERSION_COUNT,
        LISTAGG(
            TO_VARCHAR(EFF_FROM_DT) || ' to ' || TO_VARCHAR(EFF_TO_DT) ||
            ' (ACTIVE=' || COALESCE(TO_VARCHAR(ACTIVE_FLG), 'NULL') ||
            ', CURR=' || COALESCE(TO_VARCHAR(CURR_FLG), 'NULL') || ')',
            '; '
        ) WITHIN GROUP (ORDER BY EFF_FROM_DT) AS VERSION_RANGES
    FROM RETAIL_DB.TGT.DIM_STORE
    GROUP BY STORE_ID
),

UNRESOLVED_ROWS AS (

    -- Sales item
    SELECT
        'SALE_ITEM_NOT_RESOLVED_AS_OF_BUSINESS_DATE' AS CHECK_NAME,
        TO_VARCHAR(S.ITEM_ID) AS BUSINESS_KEY,
        TO_VARCHAR(S.BUSINESS_DATE) AS BUSINESS_DATE,
        IFF(
            P.ITEM_ID IS NULL,
            'ITEM_ID_NOT_FOUND_IN_DIM_ITEM',
            'NO_SCD2_VERSION_COVERS_BUSINESS_DATE'
        ) AS REASON,
        COALESCE(P.VERSION_RANGES, 'NO DIM_ITEM ROW') AS DIMENSION_VERSIONS
    FROM RETAIL_DB.TMP.SILVER_POS_SALES S
    LEFT JOIN ITEM_VERSION_PROFILE P
        ON P.ITEM_ID = S.ITEM_ID
    WHERE NOT EXISTS (
        SELECT 1
        FROM RETAIL_DB.TGT.DIM_ITEM I
        WHERE I.ITEM_ID = S.ITEM_ID
          AND S.BUSINESS_DATE BETWEEN I.EFF_FROM_DT AND I.EFF_TO_DT
    )

    UNION ALL

    -- Sales store
    SELECT
        'SALE_STORE_NOT_RESOLVED_AS_OF_BUSINESS_DATE',
        TO_VARCHAR(S.STORE_ID),
        TO_VARCHAR(S.BUSINESS_DATE),
        IFF(
            P.STORE_ID IS NULL,
            'STORE_ID_NOT_FOUND_IN_DIM_STORE',
            'NO_SCD2_VERSION_COVERS_BUSINESS_DATE'
        ),
        COALESCE(P.VERSION_RANGES, 'NO DIM_STORE ROW')
    FROM RETAIL_DB.TMP.SILVER_POS_SALES S
    LEFT JOIN STORE_VERSION_PROFILE P
        ON P.STORE_ID = S.STORE_ID
    WHERE NOT EXISTS (
        SELECT 1
        FROM RETAIL_DB.TGT.DIM_STORE D
        WHERE D.STORE_ID = S.STORE_ID
          AND S.BUSINESS_DATE BETWEEN D.EFF_FROM_DT AND D.EFF_TO_DT
    )

    UNION ALL

    -- Inventory item
    SELECT
        'INVENTORY_ITEM_NOT_RESOLVED_AS_OF_BUSINESS_DATE',
        TO_VARCHAR(S.ITEM_ID),
        TO_VARCHAR(S.BUSINESS_DATE),
        IFF(
            P.ITEM_ID IS NULL,
            'ITEM_ID_NOT_FOUND_IN_DIM_ITEM',
            'NO_SCD2_VERSION_COVERS_BUSINESS_DATE'
        ),
        COALESCE(P.VERSION_RANGES, 'NO DIM_ITEM ROW')
    FROM RETAIL_DB.TMP.SILVER_INVENTORY_SNAPSHOT S
    LEFT JOIN ITEM_VERSION_PROFILE P
        ON P.ITEM_ID = S.ITEM_ID
    WHERE NOT EXISTS (
        SELECT 1
        FROM RETAIL_DB.TGT.DIM_ITEM I
        WHERE I.ITEM_ID = S.ITEM_ID
          AND S.BUSINESS_DATE BETWEEN I.EFF_FROM_DT AND I.EFF_TO_DT
    )

    UNION ALL

    -- Inventory store
    SELECT
        'INVENTORY_STORE_NOT_RESOLVED_AS_OF_BUSINESS_DATE',
        TO_VARCHAR(S.STORE_ID),
        TO_VARCHAR(S.BUSINESS_DATE),
        IFF(
            P.STORE_ID IS NULL,
            'STORE_ID_NOT_FOUND_IN_DIM_STORE',
            'NO_SCD2_VERSION_COVERS_BUSINESS_DATE'
        ),
        COALESCE(P.VERSION_RANGES, 'NO DIM_STORE ROW')
    FROM RETAIL_DB.TMP.SILVER_INVENTORY_SNAPSHOT S
    LEFT JOIN STORE_VERSION_PROFILE P
        ON P.STORE_ID = S.STORE_ID
    WHERE NOT EXISTS (
        SELECT 1
        FROM RETAIL_DB.TGT.DIM_STORE D
        WHERE D.STORE_ID = S.STORE_ID
          AND S.BUSINESS_DATE BETWEEN D.EFF_FROM_DT AND D.EFF_TO_DT
    )

    UNION ALL

    -- Price item
    SELECT
        'PRICE_ITEM_NOT_RESOLVED_AS_OF_BUSINESS_DATE',
        TO_VARCHAR(S.ITEM_ID),
        TO_VARCHAR(S.BUSINESS_DATE),
        IFF(
            P.ITEM_ID IS NULL,
            'ITEM_ID_NOT_FOUND_IN_DIM_ITEM',
            'NO_SCD2_VERSION_COVERS_BUSINESS_DATE'
        ),
        COALESCE(P.VERSION_RANGES, 'NO DIM_ITEM ROW')
    FROM RETAIL_DB.TMP.SILVER_PRICE_SNAPSHOT S
    LEFT JOIN ITEM_VERSION_PROFILE P
        ON P.ITEM_ID = S.ITEM_ID
    WHERE NOT EXISTS (
        SELECT 1
        FROM RETAIL_DB.TGT.DIM_ITEM I
        WHERE I.ITEM_ID = S.ITEM_ID
          AND S.BUSINESS_DATE BETWEEN I.EFF_FROM_DT AND I.EFF_TO_DT
    )

    UNION ALL

    -- Price store
    SELECT
        'PRICE_STORE_NOT_RESOLVED_AS_OF_BUSINESS_DATE',
        TO_VARCHAR(S.STORE_ID),
        TO_VARCHAR(S.BUSINESS_DATE),
        IFF(
            P.STORE_ID IS NULL,
            'STORE_ID_NOT_FOUND_IN_DIM_STORE',
            'NO_SCD2_VERSION_COVERS_BUSINESS_DATE'
        ),
        COALESCE(P.VERSION_RANGES, 'NO DIM_STORE ROW')
    FROM RETAIL_DB.TMP.SILVER_PRICE_SNAPSHOT S
    LEFT JOIN STORE_VERSION_PROFILE P
        ON P.STORE_ID = S.STORE_ID
    WHERE NOT EXISTS (
        SELECT 1
        FROM RETAIL_DB.TGT.DIM_STORE D
        WHERE D.STORE_ID = S.STORE_ID
          AND S.BUSINESS_DATE BETWEEN D.EFF_FROM_DT AND D.EFF_TO_DT
    )
),

RANKED_SAMPLES AS (
    SELECT
        CHECK_NAME,
        BUSINESS_KEY || ' @ ' || COALESCE(BUSINESS_DATE, 'NULL') ||
        ' [' || REASON || ']; DIMENSION_VERSIONS=' || DIMENSION_VERSIONS
            AS DETAIL,
        ROW_NUMBER() OVER (
            PARTITION BY CHECK_NAME
            ORDER BY BUSINESS_DATE, BUSINESS_KEY
        ) AS SAMPLE_NBR
    FROM UNRESOLVED_ROWS
),

ISSUE_COUNTS AS (
    SELECT CHECK_NAME, COUNT(*) AS VIOLATION_COUNT
    FROM UNRESOLVED_ROWS
    GROUP BY CHECK_NAME
),

SAMPLE_DETAILS AS (
    SELECT
        CHECK_NAME,
        LISTAGG(DETAIL, ' || ')
            WITHIN GROUP (ORDER BY SAMPLE_NBR) AS SAMPLE_DETAILS
    FROM RANKED_SAMPLES
    WHERE SAMPLE_NBR <= 5
    GROUP BY CHECK_NAME
),

TARGET_CHECK_NAMES AS (
    SELECT COLUMN1 AS CHECK_NAME
    FROM VALUES
        ('SALE_ITEM_NOT_RESOLVED_AS_OF_BUSINESS_DATE'),
        ('SALE_STORE_NOT_RESOLVED_AS_OF_BUSINESS_DATE'),
        ('INVENTORY_ITEM_NOT_RESOLVED_AS_OF_BUSINESS_DATE'),
        ('INVENTORY_STORE_NOT_RESOLVED_AS_OF_BUSINESS_DATE'),
        ('PRICE_ITEM_NOT_RESOLVED_AS_OF_BUSINESS_DATE'),
        ('PRICE_STORE_NOT_RESOLVED_AS_OF_BUSINESS_DATE')
),

TARGET_RESULTS AS (
    SELECT
        N.CHECK_NAME,
        COALESCE(C.VIOLATION_COUNT, 0) AS VIOLATION_COUNT,
        D.SAMPLE_DETAILS
    FROM TARGET_CHECK_NAMES N
    LEFT JOIN ISSUE_COUNTS C
        ON C.CHECK_NAME = N.CHECK_NAME
    LEFT JOIN SAMPLE_DETAILS D
        ON D.CHECK_NAME = N.CHECK_NAME
)

-- Return targeted dimension checks with diagnostic samples.
SELECT
    CHECK_NAME,
    VIOLATION_COUNT,
    SAMPLE_DETAILS
FROM TARGET_RESULTS

UNION ALL

-- Calendar and customer checks.
SELECT
    'SALE_DAY_NOT_FOUND',
    COUNT(*),
    CAST(NULL AS VARCHAR)
FROM RETAIL_DB.TMP.SILVER_POS_SALES S
WHERE NOT EXISTS (
    SELECT 1
    FROM RETAIL_DB.TGT.DIM_DAY D
    WHERE D.DAY_DT = S.BUSINESS_DATE
)

UNION ALL

SELECT
    'SALE_CUSTOMER_NOT_FOUND',
    COUNT(*),
    CAST(NULL AS VARCHAR)
FROM RETAIL_DB.TMP.SILVER_POS_SALES S
WHERE S.CUSTOMER_ID IS NOT NULL
  AND NOT EXISTS (
      SELECT 1
      FROM RETAIL_DB.TGT.DIM_CUSTOMER C
      WHERE C.CUSTOMER_ID = S.CUSTOMER_ID
  )

UNION ALL

SELECT
    'INVENTORY_DAY_NOT_FOUND',
    COUNT(*),
    CAST(NULL AS VARCHAR)
FROM RETAIL_DB.TMP.SILVER_INVENTORY_SNAPSHOT S
WHERE NOT EXISTS (
    SELECT 1
    FROM RETAIL_DB.TGT.DIM_DAY D
    WHERE D.DAY_DT = S.BUSINESS_DATE
)

UNION ALL

SELECT
    'PRICE_DAY_NOT_FOUND',
    COUNT(*),
    CAST(NULL AS VARCHAR)
FROM RETAIL_DB.TMP.SILVER_PRICE_SNAPSHOT S
WHERE NOT EXISTS (
    SELECT 1
    FROM RETAIL_DB.TGT.DIM_DAY D
    WHERE D.DAY_DT = S.BUSINESS_DATE
)

UNION ALL

-- Duplicate fact-grain checks.
SELECT
    'DUPLICATE_SALE_GRAIN_IN_SILVER',
    COUNT(*),
    CAST(NULL AS VARCHAR)
FROM (
    SELECT TRANSACTION_ID, LINE_NUMBER
    FROM RETAIL_DB.TMP.SILVER_POS_SALES
    GROUP BY TRANSACTION_ID, LINE_NUMBER
    HAVING COUNT(*) > 1
)

UNION ALL

SELECT
    'DUPLICATE_INVENTORY_GRAIN_IN_SILVER',
    COUNT(*),
    CAST(NULL AS VARCHAR)
FROM (
    SELECT BUSINESS_DATE, ITEM_ID, STORE_ID
    FROM RETAIL_DB.TMP.SILVER_INVENTORY_SNAPSHOT
    GROUP BY BUSINESS_DATE, ITEM_ID, STORE_ID
    HAVING COUNT(*) > 1
)

UNION ALL

SELECT
    'DUPLICATE_PRICE_GRAIN_IN_SILVER',
    COUNT(*),
    CAST(NULL AS VARCHAR)
FROM (
    SELECT BUSINESS_DATE, ITEM_ID, STORE_ID
    FROM RETAIL_DB.TMP.SILVER_PRICE_SNAPSHOT
    GROUP BY BUSINESS_DATE, ITEM_ID, STORE_ID
    HAVING COUNT(*) > 1
)

ORDER BY CHECK_NAME;
