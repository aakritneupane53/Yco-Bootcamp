-- Pre-fact quality gate. Any non-zero VIOLATION_COUNT stops the DAG.
SELECT 'SALE_ITEM_NOT_RESOLVED_AS_OF_BUSINESS_DATE' AS CHECK_NAME, COUNT(*) AS VIOLATION_COUNT
FROM RETAIL_DB.TMP.SILVER_POS_SALES S
WHERE NOT EXISTS (
    SELECT 1 FROM RETAIL_DB.TGT.DIM_ITEM I
    WHERE I.ITEM_ID = S.ITEM_ID AND S.BUSINESS_DATE BETWEEN I.EFF_FROM_DT AND I.EFF_TO_DT
)
UNION ALL
SELECT 'SALE_STORE_NOT_RESOLVED_AS_OF_BUSINESS_DATE', COUNT(*)
FROM RETAIL_DB.TMP.SILVER_POS_SALES S
WHERE NOT EXISTS (
    SELECT 1 FROM RETAIL_DB.TGT.DIM_STORE D
    WHERE D.STORE_ID = S.STORE_ID AND S.BUSINESS_DATE BETWEEN D.EFF_FROM_DT AND D.EFF_TO_DT
)
UNION ALL
SELECT 'SALE_DAY_NOT_FOUND', COUNT(*)
FROM RETAIL_DB.TMP.SILVER_POS_SALES S
WHERE NOT EXISTS (
    SELECT 1 FROM RETAIL_DB.TGT.DIM_DAY D WHERE D.DAY_DT = S.BUSINESS_DATE
)
UNION ALL
SELECT 'SALE_CUSTOMER_NOT_FOUND', COUNT(*)
FROM RETAIL_DB.TMP.SILVER_POS_SALES S
WHERE S.CUSTOMER_ID IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM RETAIL_DB.TGT.DIM_CUSTOMER C WHERE C.CUSTOMER_ID = S.CUSTOMER_ID)
UNION ALL
SELECT 'INVENTORY_ITEM_NOT_RESOLVED_AS_OF_BUSINESS_DATE', COUNT(*)
FROM RETAIL_DB.TMP.SILVER_INVENTORY_SNAPSHOT S
WHERE NOT EXISTS (
    SELECT 1 FROM RETAIL_DB.TGT.DIM_ITEM I
    WHERE I.ITEM_ID = S.ITEM_ID AND S.BUSINESS_DATE BETWEEN I.EFF_FROM_DT AND I.EFF_TO_DT
)
UNION ALL
SELECT 'INVENTORY_STORE_NOT_RESOLVED_AS_OF_BUSINESS_DATE', COUNT(*)
FROM RETAIL_DB.TMP.SILVER_INVENTORY_SNAPSHOT S
WHERE NOT EXISTS (
    SELECT 1 FROM RETAIL_DB.TGT.DIM_STORE D
    WHERE D.STORE_ID = S.STORE_ID AND S.BUSINESS_DATE BETWEEN D.EFF_FROM_DT AND D.EFF_TO_DT
)
UNION ALL
SELECT 'INVENTORY_DAY_NOT_FOUND', COUNT(*)
FROM RETAIL_DB.TMP.SILVER_INVENTORY_SNAPSHOT S
WHERE NOT EXISTS (SELECT 1 FROM RETAIL_DB.TGT.DIM_DAY D WHERE D.DAY_DT = S.BUSINESS_DATE)
UNION ALL
SELECT 'PRICE_ITEM_NOT_RESOLVED_AS_OF_BUSINESS_DATE', COUNT(*)
FROM RETAIL_DB.TMP.SILVER_PRICE_SNAPSHOT S
WHERE NOT EXISTS (
    SELECT 1 FROM RETAIL_DB.TGT.DIM_ITEM I
    WHERE I.ITEM_ID = S.ITEM_ID AND S.BUSINESS_DATE BETWEEN I.EFF_FROM_DT AND I.EFF_TO_DT
)
UNION ALL
SELECT 'PRICE_STORE_NOT_RESOLVED_AS_OF_BUSINESS_DATE', COUNT(*)
FROM RETAIL_DB.TMP.SILVER_PRICE_SNAPSHOT S
WHERE NOT EXISTS (
    SELECT 1 FROM RETAIL_DB.TGT.DIM_STORE D
    WHERE D.STORE_ID = S.STORE_ID AND S.BUSINESS_DATE BETWEEN D.EFF_FROM_DT AND D.EFF_TO_DT
)
UNION ALL
SELECT 'PRICE_DAY_NOT_FOUND', COUNT(*)
FROM RETAIL_DB.TMP.SILVER_PRICE_SNAPSHOT S
WHERE NOT EXISTS (SELECT 1 FROM RETAIL_DB.TGT.DIM_DAY D WHERE D.DAY_DT = S.BUSINESS_DATE)
UNION ALL
SELECT 'DUPLICATE_SALE_GRAIN_IN_SILVER', COUNT(*)
FROM (
    SELECT TRANSACTION_ID, LINE_NUMBER
    FROM RETAIL_DB.TMP.SILVER_POS_SALES
    GROUP BY TRANSACTION_ID, LINE_NUMBER
    HAVING COUNT(*) > 1
)
UNION ALL
SELECT 'DUPLICATE_INVENTORY_GRAIN_IN_SILVER', COUNT(*)
FROM (
    SELECT BUSINESS_DATE, ITEM_ID, STORE_ID
    FROM RETAIL_DB.TMP.SILVER_INVENTORY_SNAPSHOT
    GROUP BY BUSINESS_DATE, ITEM_ID, STORE_ID
    HAVING COUNT(*) > 1
)
UNION ALL
SELECT 'DUPLICATE_PRICE_GRAIN_IN_SILVER', COUNT(*)
FROM (
    SELECT BUSINESS_DATE, ITEM_ID, STORE_ID
    FROM RETAIL_DB.TMP.SILVER_PRICE_SNAPSHOT
    GROUP BY BUSINESS_DATE, ITEM_ID, STORE_ID
    HAVING COUNT(*) > 1
);
