-- DIM_STORE (SCD2). Tracked attributes: STORE_NM, STORE_TYPE_C,
-- REGION_KY and ACTIVE_FLG. CITY is not part of the agreed TGT ERD.
MERGE INTO RETAIL_DB.TGT.DIM_STORE T
USING (
    WITH BASE AS (
        SELECT S.STORE_ID, S.STORE_NAME AS STORE_NM, S.STORE_TYPE AS STORE_TYPE_C,
               R.REGION_KY, S.ACTIVE_FLG, S.SNAPSHOT_DT, S.SRC_SYS_C, S.BATCH_ID
        FROM RETAIL_DB.TMP.SILVER_STORE_MASTER S
        JOIN RETAIL_DB.TGT.DIM_COUNTRY C ON C.COUNTRY_ID = S.COUNTRY_ID
        JOIN RETAIL_DB.TGT.DIM_REGION R
          ON R.COUNTRY_KY = C.COUNTRY_KY AND R.REGION_ID = S.REGION_ID
        QUALIFY ROW_NUMBER() OVER (
            PARTITION BY S.STORE_ID, S.SNAPSHOT_DT
            ORDER BY S.UPDATE_TS DESC, S.SRC_FILE_NM DESC, S.ROW_NUM DESC
        ) = 1
    ),
    COMPARED AS (
        SELECT *,
            LAG(SNAPSHOT_DT) OVER (PARTITION BY STORE_ID ORDER BY SNAPSHOT_DT) AS PREV_SNAPSHOT_DT,
            LAG(STORE_NM) OVER (PARTITION BY STORE_ID ORDER BY SNAPSHOT_DT) AS PREV_STORE_NM,
            LAG(STORE_TYPE_C) OVER (PARTITION BY STORE_ID ORDER BY SNAPSHOT_DT) AS PREV_STORE_TYPE_C,
            LAG(REGION_KY) OVER (PARTITION BY STORE_ID ORDER BY SNAPSHOT_DT) AS PREV_REGION_KY,
            LAG(ACTIVE_FLG) OVER (PARTITION BY STORE_ID ORDER BY SNAPSHOT_DT) AS PREV_ACTIVE_FLG
        FROM BASE
    ),
    CHANGES AS (
        SELECT * FROM COMPARED
        WHERE PREV_SNAPSHOT_DT IS NULL
           OR COALESCE(STORE_NM, '') <> COALESCE(PREV_STORE_NM, '')
           OR COALESCE(STORE_TYPE_C, '') <> COALESCE(PREV_STORE_TYPE_C, '')
           OR COALESCE(REGION_KY, -1) <> COALESCE(PREV_REGION_KY, -1)
           OR COALESCE(ACTIVE_FLG, FALSE) <> COALESCE(PREV_ACTIVE_FLG, FALSE)
    ),
    VERSIONED AS (
        SELECT *,
            LEAD(SNAPSHOT_DT) OVER (PARTITION BY STORE_ID ORDER BY SNAPSHOT_DT) AS NEXT_EFF_FROM_DT
        FROM CHANGES
    )
    SELECT STORE_ID, STORE_NM, STORE_TYPE_C, REGION_KY, ACTIVE_FLG,
           SNAPSHOT_DT AS EFF_FROM_DT,
           COALESCE(DATEADD(DAY, -1, NEXT_EFF_FROM_DT), '9999-12-31'::DATE) AS EFF_TO_DT,
           IFF(NEXT_EFF_FROM_DT IS NULL, TRUE, FALSE) AS CURR_FLG,
           SRC_SYS_C, BATCH_ID
    FROM VERSIONED
) S
ON T.STORE_ID = S.STORE_ID AND T.EFF_FROM_DT = S.EFF_FROM_DT
WHEN MATCHED THEN UPDATE SET
    T.STORE_NM = S.STORE_NM, T.STORE_TYPE_C = S.STORE_TYPE_C,
    T.REGION_KY = S.REGION_KY, T.ACTIVE_FLG = S.ACTIVE_FLG,
    T.EFF_TO_DT = S.EFF_TO_DT, T.CURR_FLG = S.CURR_FLG,
    T.SRC_SYS_C = S.SRC_SYS_C, T.BATCH_ID = S.BATCH_ID,
    T.UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    STORE_ID, STORE_NM, STORE_TYPE_C, REGION_KY, ACTIVE_FLG, CURR_FLG,
    EFF_FROM_DT, EFF_TO_DT, SRC_SYS_C, BATCH_ID, INSERT_TS, UPDATE_TS
) VALUES (
    S.STORE_ID, S.STORE_NM, S.STORE_TYPE_C, S.REGION_KY, S.ACTIVE_FLG, S.CURR_FLG,
    S.EFF_FROM_DT, S.EFF_TO_DT, S.SRC_SYS_C, S.BATCH_ID,
    CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP()
);
