
-- DIM_CUSTOMER (SCD1).
-- Silver LOYALTY_TIER maps directly to TGT LOYALTY_TIER.
-- Customer name, city and registration date remain in TMP because they are
-- not part of the agreed TGT dimension design.

MERGE INTO RETAIL_DB.TGT.DIM_CUSTOMER T
USING (
    SELECT
        CUSTOMER_ID,
        LOYALTY_TIER,
        ACTIVE_FLG,
        SRC_SYS_C,
        BATCH_ID
    FROM RETAIL_DB.TMP.SILVER_CUSTOMER_MASTER
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY CUSTOMER_ID
        ORDER BY UPDATE_TS DESC, SRC_FILE_NM DESC, ROW_NUM DESC
    ) = 1
) S
ON T.CUSTOMER_ID = S.CUSTOMER_ID

WHEN MATCHED THEN UPDATE SET
    T.LOYALTY_TIER = S.LOYALTY_TIER,
    T.ACTIVE_FLG = S.ACTIVE_FLG,
    T.SRC_SYS_C = S.SRC_SYS_C,
    T.BATCH_ID = S.BATCH_ID,
    T.UPDATE_TS = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    CUSTOMER_ID,
    LOYALTY_TIER,
    ACTIVE_FLG,
    SRC_SYS_C,
    BATCH_ID,
    INSERT_TS,
    UPDATE_TS
)
VALUES (
    S.CUSTOMER_ID,
    S.LOYALTY_TIER,
    S.ACTIVE_FLG,
    S.SRC_SYS_C,
    S.BATCH_ID,
    CURRENT_TIMESTAMP(),
    CURRENT_TIMESTAMP()
);
