-- Post-load quality and reconciliation gate. Any non-zero result fails the DAG.
SELECT 'ITEM_WITHOUT_EXACTLY_ONE_CURRENT_VERSION' AS CHECK_NAME, COUNT(*) AS VIOLATION_COUNT
FROM (
    SELECT B.ITEM_ID
    FROM (SELECT DISTINCT ITEM_ID FROM RETAIL_DB.TMP.SILVER_ITEM_MASTER) B
    LEFT JOIN RETAIL_DB.TGT.DIM_ITEM D
      ON D.ITEM_ID = B.ITEM_ID AND D.CURR_FLG = TRUE
    GROUP BY B.ITEM_ID
    HAVING COUNT(D.ITEM_KY) <> 1
)
UNION ALL
SELECT 'STORE_WITHOUT_EXACTLY_ONE_CURRENT_VERSION', COUNT(*)
FROM (
    SELECT B.STORE_ID
    FROM (SELECT DISTINCT STORE_ID FROM RETAIL_DB.TMP.SILVER_STORE_MASTER) B
    LEFT JOIN RETAIL_DB.TGT.DIM_STORE D
      ON D.STORE_ID = B.STORE_ID AND D.CURR_FLG = TRUE
    GROUP BY B.STORE_ID
    HAVING COUNT(D.STORE_KY) <> 1
)
UNION ALL
SELECT 'DUPLICATE_SALE_GRAIN', COUNT(*)
FROM (
    SELECT TRANSACTION_ID, LINE_NBR FROM RETAIL_DB.TGT.FCT_SALE
    GROUP BY TRANSACTION_ID, LINE_NBR HAVING COUNT(*) > 1
)
UNION ALL
SELECT 'DUPLICATE_INVENTORY_GRAIN', COUNT(*)
FROM (
    SELECT ITEM_KY, STORE_KY, DAY_KY FROM RETAIL_DB.TGT.FCT_INVENTORY
    GROUP BY ITEM_KY, STORE_KY, DAY_KY HAVING COUNT(*) > 1
)
UNION ALL
SELECT 'DUPLICATE_PRICE_VERSION_GRAIN', COUNT(*)
FROM (
    SELECT ITEM_KY, STORE_KY, DAY_KY FROM RETAIL_DB.TGT.FCT_PRICE
    GROUP BY ITEM_KY, STORE_KY, DAY_KY HAVING COUNT(*) > 1
)
UNION ALL
SELECT 'SALES_ROW_COUNT_RECONCILIATION',
       ABS((SELECT COUNT(*) FROM RETAIL_DB.TMP.SILVER_POS_SALES)
         - (SELECT COUNT(*) FROM RETAIL_DB.TGT.FCT_SALE))
UNION ALL
SELECT 'SALES_AMOUNT_RECONCILIATION',
       IFF(ABS(COALESCE((SELECT SUM(SALES_AMT) FROM RETAIL_DB.TMP.SILVER_POS_SALES), 0)
             - COALESCE((SELECT SUM(SALES_AMT) FROM RETAIL_DB.TGT.FCT_SALE), 0)) > 0.01, 1, 0)
UNION ALL
SELECT 'INVENTORY_ROW_COUNT_RECONCILIATION',
       ABS((SELECT COUNT(*) FROM RETAIL_DB.TMP.SILVER_INVENTORY_SNAPSHOT)
         - (SELECT COUNT(*) FROM RETAIL_DB.TGT.FCT_INVENTORY))
UNION ALL
SELECT 'AGGREGATE_SALES_AMOUNT_RECONCILIATION',
       IFF(ABS(COALESCE((SELECT SUM(SALES_AMT) FROM RETAIL_DB.TGT.FCT_SALE), 0)
             - COALESCE((SELECT SUM(SALES_AMT) FROM RETAIL_DB.MARTS.AGG_FCT_PRODUCT_SALES_MON), 0)) > 0.01, 1, 0)
UNION ALL
SELECT 'SALES_FACT_MISSING_DAY_DIMENSION', COUNT(*)
FROM RETAIL_DB.TGT.FCT_SALE F
LEFT JOIN RETAIL_DB.TGT.DIM_DAY D ON D.DAY_KY = F.DAY_KY
WHERE D.DAY_KY IS NULL
UNION ALL
SELECT 'INVENTORY_FACT_MISSING_DAY_DIMENSION', COUNT(*)
FROM RETAIL_DB.TGT.FCT_INVENTORY F
LEFT JOIN RETAIL_DB.TGT.DIM_DAY D ON D.DAY_KY = F.DAY_KY
WHERE D.DAY_KY IS NULL
UNION ALL
SELECT 'SALES_FACT_MISSING_ITEM_OR_STORE_DIMENSION', COUNT(*)
FROM RETAIL_DB.TGT.FCT_SALE F
LEFT JOIN RETAIL_DB.TGT.DIM_ITEM I ON I.ITEM_KY = F.ITEM_KY
LEFT JOIN RETAIL_DB.TGT.DIM_STORE S ON S.STORE_KY = F.STORE_KY
WHERE I.ITEM_KY IS NULL OR S.STORE_KY IS NULL
UNION ALL
SELECT 'INVENTORY_FACT_MISSING_ITEM_OR_STORE_DIMENSION', COUNT(*)
FROM RETAIL_DB.TGT.FCT_INVENTORY F
LEFT JOIN RETAIL_DB.TGT.DIM_ITEM I ON I.ITEM_KY = F.ITEM_KY
LEFT JOIN RETAIL_DB.TGT.DIM_STORE S ON S.STORE_KY = F.STORE_KY
WHERE I.ITEM_KY IS NULL OR S.STORE_KY IS NULL
UNION ALL
SELECT 'PRICE_FACT_MISSING_ITEM_STORE_OR_DAY_DIMENSION', COUNT(*)
FROM RETAIL_DB.TGT.FCT_PRICE F
LEFT JOIN RETAIL_DB.TGT.DIM_ITEM I ON I.ITEM_KY = F.ITEM_KY
LEFT JOIN RETAIL_DB.TGT.DIM_STORE S ON S.STORE_KY = F.STORE_KY
LEFT JOIN RETAIL_DB.TGT.DIM_DAY D ON D.DAY_KY = F.DAY_KY
WHERE I.ITEM_KY IS NULL OR S.STORE_KY IS NULL OR D.DAY_KY IS NULL
UNION ALL
SELECT 'INVALID_ITEM_EFFECTIVE_DATE_RANGE', COUNT(*)
FROM RETAIL_DB.TGT.DIM_ITEM
WHERE EFF_FROM_DT > EFF_TO_DT
UNION ALL
SELECT 'INVALID_STORE_EFFECTIVE_DATE_RANGE', COUNT(*)
FROM RETAIL_DB.TGT.DIM_STORE
WHERE EFF_FROM_DT > EFF_TO_DT
UNION ALL
SELECT 'INVALID_PRICE_EFFECTIVE_DATE_RANGE', COUNT(*)
FROM RETAIL_DB.TGT.FCT_PRICE
WHERE EFF_FROM_DT > EFF_TO_DT
UNION ALL
SELECT 'PRICE_ACTIVE_FLAG_MISMATCH', COUNT(*)
FROM RETAIL_DB.TGT.FCT_PRICE
WHERE ACTIVE_FLG <> (EFF_TO_DT = '9999-12-31'::DATE);
