-- ---------------------------------------------------------------------------
-- DETAILED FACTS
-- FCT_SALE: one POS transaction line (TRANSACTION_ID + LINE_NBR)
-- FCT_INVENTORY: one item + store + business date
-- FCT_PRICE: one price version per item + store, starting on a day
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS RETAIL_DB.TGT.FCT_SALE (
    SALES_KY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1,
    ITEM_KY NUMBER(38,0) NOT NULL,
    STORE_KY NUMBER(38,0) NOT NULL,
    DAY_KY NUMBER(38,0) NOT NULL,
    CUSTOMER_KY NUMBER(38,0),
    TRANSACTION_ID VARCHAR(150) NOT NULL,
    LINE_NBR NUMBER(38,0) NOT NULL,
    SOLD_QTY NUMBER(18,3),
    SELLING_PRICE_AMT NUMBER(18,2),
    SALES_AMT NUMBER(18,2),
    DISCOUNT_AMT NUMBER(18,2),
    COST_AMT NUMBER(18,2),
    SRC_SYS_C VARCHAR(100),
    BATCH_ID VARCHAR(100),
    INSERT_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATE_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_FCT_SALE PRIMARY KEY (SALES_KY),
    CONSTRAINT FK_FCT_SALE_ITEM FOREIGN KEY (ITEM_KY)
        REFERENCES RETAIL_DB.TGT.DIM_ITEM (ITEM_KY),
    CONSTRAINT FK_FCT_SALE_STORE FOREIGN KEY (STORE_KY)
        REFERENCES RETAIL_DB.TGT.DIM_STORE (STORE_KY),
    CONSTRAINT FK_FCT_SALE_DAY FOREIGN KEY (DAY_KY)
        REFERENCES RETAIL_DB.TGT.DIM_DAY (DAY_KY),
    CONSTRAINT FK_FCT_SALE_CUSTOMER FOREIGN KEY (CUSTOMER_KY)
        REFERENCES RETAIL_DB.TGT.DIM_CUSTOMER (CUSTOMER_KY)
);

CREATE TABLE IF NOT EXISTS RETAIL_DB.TGT.FCT_INVENTORY (
