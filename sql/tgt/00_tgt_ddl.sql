-- ============================================================================
-- RETAIL DATA ENGINEERING PROJECT - TGT + MARTS DDL
-- Sources: RETAIL_DB.TMP (Silver)
-- Targets: RETAIL_DB.TGT (dimensions + detailed facts)
--          RETAIL_DB.MARTS (monthly aggregate)
--
-- Only attributes supported by TMP or explicitly derived from it are included.
-- PK/FK/UNIQUE declarations document the model; standard Snowflake tables do
-- not enforce these constraints.
-- ============================================================================

CREATE SCHEMA IF NOT EXISTS RETAIL_DB.TGT;
CREATE SCHEMA IF NOT EXISTS RETAIL_DB.MARTS;

-- ---------------------------------------------------------------------------
-- LOCATION HIERARCHY: COUNTRY -> REGION -> STORE
-- COUNTRY / REGION = SCD1; STORE = SCD2
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS RETAIL_DB.TGT.DIM_COUNTRY (
    COUNTRY_KY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1,
    COUNTRY_ID VARCHAR(100) NOT NULL,
    COUNTRY_NM VARCHAR(255),
    ACTIVE_FLG BOOLEAN,
    SRC_SYS_C VARCHAR(100),
    BATCH_ID VARCHAR(100),
    INSERT_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATE_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DIM_COUNTRY PRIMARY KEY (COUNTRY_KY),
    CONSTRAINT UQ_DIM_COUNTRY_BK UNIQUE (COUNTRY_ID)
);

CREATE TABLE IF NOT EXISTS RETAIL_DB.TGT.DIM_REGION (
    REGION_KY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1,
    REGION_ID VARCHAR(100) NOT NULL,
    REGION_NM VARCHAR(255),
    COUNTRY_KY NUMBER(38,0) NOT NULL,
    ACTIVE_FLG BOOLEAN,
    SRC_SYS_C VARCHAR(100),
    BATCH_ID VARCHAR(100),
    INSERT_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATE_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DIM_REGION PRIMARY KEY (REGION_KY),
    CONSTRAINT UQ_DIM_REGION_BK UNIQUE (COUNTRY_KY, REGION_ID),
    CONSTRAINT FK_DIM_REGION_COUNTRY FOREIGN KEY (COUNTRY_KY)
        REFERENCES RETAIL_DB.TGT.DIM_COUNTRY (COUNTRY_KY)
);

CREATE TABLE IF NOT EXISTS RETAIL_DB.TGT.DIM_STORE (
    STORE_KY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1,
    STORE_ID VARCHAR(100) NOT NULL,
    STORE_NM VARCHAR(255),
    STORE_TYPE_C VARCHAR(100),
    REGION_KY NUMBER(38,0) NOT NULL,
    ACTIVE_FLG BOOLEAN,
    CURR_FLG BOOLEAN DEFAULT TRUE,
    EFF_FROM_DT DATE NOT NULL,
    EFF_TO_DT DATE NOT NULL DEFAULT '9999-12-31',
    SRC_SYS_C VARCHAR(100),
    BATCH_ID VARCHAR(100),
    INSERT_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATE_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DIM_STORE PRIMARY KEY (STORE_KY),
    CONSTRAINT FK_DIM_STORE_REGION FOREIGN KEY (REGION_KY)
        REFERENCES RETAIL_DB.TGT.DIM_REGION (REGION_KY)
);

