-- DIM_BRAND (SCD1).
MERGE INTO RETAIL_DB.TGT.DIM_BRAND T
USING (
    WITH LATEST_ITEM AS (
        SELECT ITEM_ID, BRAND_ID, BRAND_NAME, ACTIVE_FLG, SRC_SYS_C, BATCH_ID, SNAPSHOT_DT
        FROM RETAIL_DB.TMP.SILVER_ITEM_MASTER
        QUALIFY ROW_NUMBER() OVER (
            PARTITION BY ITEM_ID
            ORDER BY SNAPSHOT_DT DESC, UPDATE_TS DESC, SRC_FILE_NM DESC, ROW_NUM DESC
        ) = 1
    ),
    NAME_ROWS AS (
        SELECT BRAND_ID, BRAND_NAME, SRC_SYS_C, BATCH_ID
        FROM LATEST_ITEM
        QUALIFY ROW_NUMBER() OVER (
            PARTITION BY BRAND_ID ORDER BY SNAPSHOT_DT DESC, ITEM_ID
        ) = 1
    ),
    STATUS_ROWS AS (
        SELECT BRAND_ID, BOOLOR_AGG(COALESCE(ACTIVE_FLG, FALSE)) AS ACTIVE_FLG
        FROM LATEST_ITEM GROUP BY BRAND_ID
    )
    SELECT N.BRAND_ID, N.BRAND_NAME AS BRAND_NM, S.ACTIVE_FLG, N.SRC_SYS_C, N.BATCH_ID
    FROM NAME_ROWS N JOIN STATUS_ROWS S USING (BRAND_ID)
) S
ON T.BRAND_ID = S.BRAND_ID
WHEN MATCHED THEN UPDATE SET
    T.BRAND_NM = S.BRAND_NM, T.ACTIVE_FLG = S.ACTIVE_FLG,
    T.SRC_SYS_C = S.SRC_SYS_C, T.BATCH_ID = S.BATCH_ID,
    T.UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    BRAND_ID, BRAND_NM, ACTIVE_FLG, SRC_SYS_C, BATCH_ID, INSERT_TS, UPDATE_TS
) VALUES (
    S.BRAND_ID, S.BRAND_NM, S.ACTIVE_FLG, S.SRC_SYS_C, S.BATCH_ID,
    CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP()
);
