-- FCT_PRICE is a positional/validity fact. Daily snapshots are collapsed to
-- price-change events. A new row is also created when the applicable SCD2
-- item/store version changes, even when the numeric price remains unchanged.
-- The next event closes the previous effective period.
MERGE INTO RETAIL_DB.TGT.FCT_PRICE T
USING (
    WITH BASE AS (
        SELECT BUSINESS_DATE, ITEM_ID, STORE_ID, SELLING_PRICE_AMT, UNIT_COST_AMT,
               SRC_SYS_C, BATCH_ID
        FROM RETAIL_DB.TMP.SILVER_PRICE_SNAPSHOT
        QUALIFY ROW_NUMBER() OVER (
            PARTITION BY BUSINESS_DATE, ITEM_ID, STORE_ID
            ORDER BY UPDATE_TS DESC, SRC_FILE_NM DESC, ROW_NUM DESC
        ) = 1
    ),
    KEYED AS (
        SELECT
            B.*,
            I.ITEM_KY,
            ST.STORE_KY,
            D.DAY_KY
        FROM BASE B
        JOIN RETAIL_DB.TGT.DIM_ITEM I
          ON I.ITEM_ID = B.ITEM_ID
         AND B.BUSINESS_DATE BETWEEN I.EFF_FROM_DT AND I.EFF_TO_DT
        JOIN RETAIL_DB.TGT.DIM_STORE ST
          ON ST.STORE_ID = B.STORE_ID
         AND B.BUSINESS_DATE BETWEEN ST.EFF_FROM_DT AND ST.EFF_TO_DT
        JOIN RETAIL_DB.TGT.DIM_DAY D ON D.DAY_DT = B.BUSINESS_DATE
    ),
    COMPARED AS (
        SELECT *,
            LAG(BUSINESS_DATE) OVER (
                PARTITION BY ITEM_ID, STORE_ID ORDER BY BUSINESS_DATE
            ) AS PREV_BUSINESS_DATE,
            LAG(SELLING_PRICE_AMT) OVER (
                PARTITION BY ITEM_ID, STORE_ID ORDER BY BUSINESS_DATE
            ) AS PREV_SELLING_PRICE_AMT,
            LAG(UNIT_COST_AMT) OVER (
                PARTITION BY ITEM_ID, STORE_ID ORDER BY BUSINESS_DATE
            ) AS PREV_UNIT_COST_AMT,
            LAG(ITEM_KY) OVER (
                PARTITION BY ITEM_ID, STORE_ID ORDER BY BUSINESS_DATE
            ) AS PREV_ITEM_KY,
            LAG(STORE_KY) OVER (
                PARTITION BY ITEM_ID, STORE_ID ORDER BY BUSINESS_DATE
            ) AS PREV_STORE_KY
        FROM KEYED
    ),
    CHANGES AS (
        SELECT * FROM COMPARED
        WHERE PREV_BUSINESS_DATE IS NULL
           OR COALESCE(SELLING_PRICE_AMT, -999999999) <> COALESCE(PREV_SELLING_PRICE_AMT, -999999999)
           OR COALESCE(UNIT_COST_AMT, -999999999) <> COALESCE(PREV_UNIT_COST_AMT, -999999999)
           OR ITEM_KY <> PREV_ITEM_KY
           OR STORE_KY <> PREV_STORE_KY
    ),
    VERSIONED AS (
        SELECT *,
            LEAD(BUSINESS_DATE) OVER (
                PARTITION BY ITEM_ID, STORE_ID ORDER BY BUSINESS_DATE
            ) AS NEXT_EFF_FROM_DT
        FROM CHANGES
    )
    SELECT
        ITEM_KY, STORE_KY, DAY_KY,
        SELLING_PRICE_AMT, UNIT_COST_AMT,
        BUSINESS_DATE AS EFF_FROM_DT,
        COALESCE(DATEADD(DAY, -1, NEXT_EFF_FROM_DT), '9999-12-31'::DATE) AS EFF_TO_DT,
        IFF(NEXT_EFF_FROM_DT IS NULL, TRUE, FALSE) AS ACTIVE_FLG,
        SRC_SYS_C, BATCH_ID
    FROM VERSIONED
) S
ON T.ITEM_KY = S.ITEM_KY AND T.STORE_KY = S.STORE_KY AND T.DAY_KY = S.DAY_KY
WHEN MATCHED THEN UPDATE SET
    T.SELLING_PRICE_AMT = S.SELLING_PRICE_AMT,
    T.UNIT_COST_AMT = S.UNIT_COST_AMT,
    T.ACTIVE_FLG = S.ACTIVE_FLG,
    T.EFF_FROM_DT = S.EFF_FROM_DT,
    T.EFF_TO_DT = S.EFF_TO_DT,
    T.SRC_SYS_C = S.SRC_SYS_C,
    T.BATCH_ID = S.BATCH_ID,
    T.UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    ITEM_KY, STORE_KY, DAY_KY, SELLING_PRICE_AMT, UNIT_COST_AMT, ACTIVE_FLG,
    EFF_FROM_DT, EFF_TO_DT, SRC_SYS_C, BATCH_ID, INSERT_TS, UPDATE_TS
) VALUES (
    S.ITEM_KY, S.STORE_KY, S.DAY_KY, S.SELLING_PRICE_AMT, S.UNIT_COST_AMT,
    S.ACTIVE_FLG, S.EFF_FROM_DT, S.EFF_TO_DT, S.SRC_SYS_C, S.BATCH_ID,
    CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP()
);
