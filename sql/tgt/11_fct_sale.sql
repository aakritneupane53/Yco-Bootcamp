-- FCT_SALE: one row per (TRANSACTION_ID, LINE_NUMBER).
-- Type 2 item/store keys are resolved using the sale business date.
-- Remove target grain rows no longer present in the Silver source.
DELETE FROM RETAIL_DB.TGT.FCT_SALE T
WHERE NOT EXISTS (
    SELECT 1
    FROM RETAIL_DB.TMP.SILVER_POS_SALES S
    WHERE S.TRANSACTION_ID = T.TRANSACTION_ID
      AND S.LINE_NUMBER = T.LINE_NBR
);

MERGE INTO RETAIL_DB.TGT.FCT_SALE T
USING (
    SELECT
        I.ITEM_KY, ST.STORE_KY, D.DAY_KY, C.CUSTOMER_KY,
        S.TRANSACTION_ID, S.LINE_NUMBER AS LINE_NBR,
        S.SOLD_QTY, S.SELLING_PRICE_AMT, S.SALES_AMT, S.DISCOUNT_AMT, S.COST_AMT,
        S.SRC_SYS_C, S.BATCH_ID
    FROM RETAIL_DB.TMP.SILVER_POS_SALES S
    JOIN RETAIL_DB.TGT.DIM_ITEM I
      ON I.ITEM_ID = S.ITEM_ID AND S.BUSINESS_DATE BETWEEN I.EFF_FROM_DT AND I.EFF_TO_DT
    JOIN RETAIL_DB.TGT.DIM_STORE ST
      ON ST.STORE_ID = S.STORE_ID AND S.BUSINESS_DATE BETWEEN ST.EFF_FROM_DT AND ST.EFF_TO_DT
    JOIN RETAIL_DB.TGT.DIM_DAY D ON D.DAY_DT = S.BUSINESS_DATE
    LEFT JOIN RETAIL_DB.TGT.DIM_CUSTOMER C ON C.CUSTOMER_ID = S.CUSTOMER_ID
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY S.TRANSACTION_ID, S.LINE_NUMBER
        ORDER BY S.UPDATE_TS DESC, S.SRC_FILE_NM DESC, S.ROW_NUM DESC
    ) = 1
) S
ON T.TRANSACTION_ID = S.TRANSACTION_ID AND T.LINE_NBR = S.LINE_NBR
WHEN MATCHED THEN UPDATE SET
    T.ITEM_KY = S.ITEM_KY, T.STORE_KY = S.STORE_KY, T.DAY_KY = S.DAY_KY,
    T.CUSTOMER_KY = S.CUSTOMER_KY, T.SOLD_QTY = S.SOLD_QTY,
    T.SELLING_PRICE_AMT = S.SELLING_PRICE_AMT, T.SALES_AMT = S.SALES_AMT,
    T.DISCOUNT_AMT = S.DISCOUNT_AMT, T.COST_AMT = S.COST_AMT,
    T.SRC_SYS_C = S.SRC_SYS_C, T.BATCH_ID = S.BATCH_ID,
    T.UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    ITEM_KY, STORE_KY, DAY_KY, CUSTOMER_KY, TRANSACTION_ID, LINE_NBR,
    SOLD_QTY, SELLING_PRICE_AMT, SALES_AMT, DISCOUNT_AMT, COST_AMT,
    SRC_SYS_C, BATCH_ID, INSERT_TS, UPDATE_TS
) VALUES (
    S.ITEM_KY, S.STORE_KY, S.DAY_KY, S.CUSTOMER_KY, S.TRANSACTION_ID, S.LINE_NBR,
    S.SOLD_QTY, S.SELLING_PRICE_AMT, S.SALES_AMT, S.DISCOUNT_AMT, S.COST_AMT,
    S.SRC_SYS_C, S.BATCH_ID, CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP()
);
