-- DIM_COUNTRY (SCD1). ACTIVE_FLG means at least one latest store in the
-- country is active; the source feeds do not carry a separate country status.
MERGE INTO RETAIL_DB.TGT.DIM_COUNTRY T
USING (
    WITH LATEST_STORE AS (
        SELECT COUNTRY_ID, COUNTRY_NAME, ACTIVE_FLG, SRC_SYS_C, BATCH_ID,
               SNAPSHOT_DT, STORE_ID
        FROM RETAIL_DB.TMP.SILVER_STORE_MASTER
        QUALIFY ROW_NUMBER() OVER (
            PARTITION BY STORE_ID
            ORDER BY SNAPSHOT_DT DESC, UPDATE_TS DESC, SRC_FILE_NM DESC, ROW_NUM DESC
        ) = 1
    ),
    COUNTRY_NAME AS (
        SELECT COUNTRY_ID, COUNTRY_NAME, SRC_SYS_C, BATCH_ID
        FROM LATEST_STORE
        QUALIFY ROW_NUMBER() OVER (
            PARTITION BY COUNTRY_ID
            ORDER BY SNAPSHOT_DT DESC, STORE_ID
        ) = 1
    ),
    COUNTRY_STATUS AS (
        SELECT COUNTRY_ID, BOOLOR_AGG(COALESCE(ACTIVE_FLG, FALSE)) AS ACTIVE_FLG
        FROM LATEST_STORE GROUP BY COUNTRY_ID
    )
    SELECT N.COUNTRY_ID, N.COUNTRY_NAME AS COUNTRY_NM, S.ACTIVE_FLG,
           N.SRC_SYS_C, N.BATCH_ID
    FROM COUNTRY_NAME N
    JOIN COUNTRY_STATUS S USING (COUNTRY_ID)
) S
ON T.COUNTRY_ID = S.COUNTRY_ID
WHEN MATCHED THEN UPDATE SET
    T.COUNTRY_NM = S.COUNTRY_NM,
    T.ACTIVE_FLG = S.ACTIVE_FLG,
    T.SRC_SYS_C = S.SRC_SYS_C,
    T.BATCH_ID = S.BATCH_ID,
    T.UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    COUNTRY_ID, COUNTRY_NM, ACTIVE_FLG, SRC_SYS_C, BATCH_ID, INSERT_TS, UPDATE_TS
) VALUES (
    S.COUNTRY_ID, S.COUNTRY_NM, S.ACTIVE_FLG, S.SRC_SYS_C, S.BATCH_ID,
    CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP()
);
