-- Monthly mart: one row per item version + store version + month.
-- Recompute from the detailed sales fact so corrections flow through on rerun.
MERGE INTO RETAIL_DB.MARTS.AGG_FCT_PRODUCT_SALES_MON T
USING (
    SELECT
        F.ITEM_KY, F.STORE_KY, D.MONTH_KY,
        COUNT(*) AS SALES_LINE_CNT,
        SUM(F.SOLD_QTY) AS SOLD_QTY,
        SUM(F.SALES_AMT) AS SALES_AMT,
        SUM(F.DISCOUNT_AMT) AS DISCOUNT_AMT,
        SUM(F.COST_AMT) AS COST_AMT,
        'RETAIL_TGT' AS SRC_SYS_C,
        MAX(F.BATCH_ID) AS BATCH_ID
    FROM RETAIL_DB.TGT.FCT_SALE F
    JOIN RETAIL_DB.TGT.DIM_DAY D ON D.DAY_KY = F.DAY_KY
    GROUP BY F.ITEM_KY, F.STORE_KY, D.MONTH_KY
) S
ON T.ITEM_KY = S.ITEM_KY AND T.STORE_KY = S.STORE_KY AND T.MONTH_KY = S.MONTH_KY
WHEN MATCHED THEN UPDATE SET
    T.SALES_LINE_CNT = S.SALES_LINE_CNT, T.SOLD_QTY = S.SOLD_QTY,
    T.SALES_AMT = S.SALES_AMT, T.DISCOUNT_AMT = S.DISCOUNT_AMT,
    T.COST_AMT = S.COST_AMT, T.SRC_SYS_C = S.SRC_SYS_C,
    T.BATCH_ID = S.BATCH_ID, T.UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    ITEM_KY, STORE_KY, MONTH_KY, SALES_LINE_CNT, SOLD_QTY, SALES_AMT,
    DISCOUNT_AMT, COST_AMT, SRC_SYS_C, BATCH_ID, INSERT_TS, UPDATE_TS
) VALUES (
    S.ITEM_KY, S.STORE_KY, S.MONTH_KY, S.SALES_LINE_CNT, S.SOLD_QTY,
    S.SALES_AMT, S.DISCOUNT_AMT, S.COST_AMT, S.SRC_SYS_C, S.BATCH_ID,
    CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP()
);

-- Remove stale item/store/month groups for months represented by the current
-- Silver POS scope. Using Silver dates also catches the case where a complete
-- item/store group was removed from TGT facts by a corrected source batch.
DELETE FROM RETAIL_DB.MARTS.AGG_FCT_PRODUCT_SALES_MON T
WHERE EXISTS (
    SELECT 1
    FROM RETAIL_DB.TMP.SILVER_POS_SALES S
    JOIN RETAIL_DB.TGT.DIM_MONTH M
      ON M.MONTH_ID = YEAR(S.BUSINESS_DATE) * 100 + MONTH(S.BUSINESS_DATE)
    WHERE M.MONTH_KY = T.MONTH_KY
)
AND NOT EXISTS (
    SELECT 1
    FROM RETAIL_DB.TGT.FCT_SALE F
    JOIN RETAIL_DB.TGT.DIM_DAY D ON D.DAY_KY = F.DAY_KY
    WHERE F.ITEM_KY = T.ITEM_KY
      AND F.STORE_KY = T.STORE_KY
      AND D.MONTH_KY = T.MONTH_KY
);
