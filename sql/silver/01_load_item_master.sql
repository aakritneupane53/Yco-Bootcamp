
USE DATABASE RETAIL_DB;
USE SCHEMA TMP;


CREATE OR REPLACE TEMP TABLE TMP_ITEM_MASTER_WORK AS
WITH BRONZE_DEDUP AS (
    SELECT
        ITEM_ID,
        ITEM_NAME,
        SUBCATEGORY_ID,
        SUBCATEGORY_NAME,
        CATEGORY_ID,
        CATEGORY_NAME,
        BRAND_ID,
        BRAND_NAME,
        UNIT_OF_MEASURE,
        ACTIVE_FLG,
        SRC_FILE_NM,
        ROW_NUM,
        INGEST_TS AS SOURCE_INGEST_TS,
        BATCH_ID
    FROM RETAIL_DB.STG.STG_ITEM_MASTER
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY SRC_FILE_NM, ROW_NUM
        ORDER BY INGEST_TS DESC, BATCH_ID DESC
    ) = 1
),
NORMALIZED AS (
    SELECT
        -- Original values for quarantine/audit.
        ITEM_ID             AS RAW_ITEM_ID,
        ITEM_NAME           AS RAW_ITEM_NAME,
        SUBCATEGORY_ID      AS RAW_SUBCATEGORY_ID,
        SUBCATEGORY_NAME    AS RAW_SUBCATEGORY_NAME,
        CATEGORY_ID         AS RAW_CATEGORY_ID,
        CATEGORY_NAME       AS RAW_CATEGORY_NAME,
        BRAND_ID            AS RAW_BRAND_ID,
        BRAND_NAME          AS RAW_BRAND_NAME,
        UNIT_OF_MEASURE     AS RAW_UNIT_OF_MEASURE,
        ACTIVE_FLG          AS RAW_ACTIVE_FLG,

        -- Cleaned business keys and descriptive attributes.
        NULLIF(UPPER(TRIM(ITEM_ID)), '')             AS ITEM_ID,
        NULLIF(TRIM(ITEM_NAME), '')                  AS ITEM_NAME,
        NULLIF(UPPER(TRIM(SUBCATEGORY_ID)), '')      AS SUBCATEGORY_ID,
        NULLIF(TRIM(SUBCATEGORY_NAME), '')           AS SUBCATEGORY_NAME,
        NULLIF(UPPER(TRIM(CATEGORY_ID)), '')         AS CATEGORY_ID,
        NULLIF(TRIM(CATEGORY_NAME), '')              AS CATEGORY_NAME,
        NULLIF(UPPER(TRIM(BRAND_ID)), '')            AS BRAND_ID,
        NULLIF(UPPER(TRIM(BRAND_NAME)), '')          AS BRAND_NAME,
        NULLIF(UPPER(TRIM(UNIT_OF_MEASURE)), '')     AS UNIT_OF_MEASURE,

        CASE
            WHEN UPPER(TRIM(ACTIVE_FLG)) IN ('1', 'TRUE', 'T', 'Y', 'YES')
                THEN TRUE
            WHEN UPPER(TRIM(ACTIVE_FLG)) IN ('0', 'FALSE', 'F', 'N', 'NO')
                THEN FALSE
            ELSE NULL
        END AS ACTIVE_FLG,

        TRY_TO_DATE(
            REGEXP_SUBSTR(SRC_FILE_NM, '[0-9]{8}'),
            'YYYYMMDD'
        ) AS SNAPSHOT_DT,

        SRC_FILE_NM,
        ROW_NUM,
        SOURCE_INGEST_TS,
        BATCH_ID
    FROM BRONZE_DEDUP
),
HASHED AS (
    SELECT
        N.*,
        SHA2(
            TO_JSON(OBJECT_CONSTRUCT_KEEP_NULL(
                'ITEM_ID', RAW_ITEM_ID,
                'ITEM_NAME', RAW_ITEM_NAME,
                'SUBCATEGORY_ID', RAW_SUBCATEGORY_ID,
                'SUBCATEGORY_NAME', RAW_SUBCATEGORY_NAME,
                'CATEGORY_ID', RAW_CATEGORY_ID,
                'CATEGORY_NAME', RAW_CATEGORY_NAME,
                'BRAND_ID', RAW_BRAND_ID,
                'BRAND_NAME', RAW_BRAND_NAME,
                'UNIT_OF_MEASURE', RAW_UNIT_OF_MEASURE,
                'ACTIVE_FLG', RAW_ACTIVE_FLG
            )),
            256
        ) AS SRC_ROW_HASH,
        SHA2(
            TO_JSON(OBJECT_CONSTRUCT_KEEP_NULL(
                'ITEM_ID', ITEM_ID,
                'ITEM_NAME', ITEM_NAME,
                'SUBCATEGORY_ID', SUBCATEGORY_ID,
                'SUBCATEGORY_NAME', SUBCATEGORY_NAME,
                'CATEGORY_ID', CATEGORY_ID,
                'CATEGORY_NAME', CATEGORY_NAME,
                'BRAND_ID', BRAND_ID,
                'BRAND_NAME', BRAND_NAME,
                'UNIT_OF_MEASURE', UNIT_OF_MEASURE,
                'ACTIVE_FLG', ACTIVE_FLG,
                'SNAPSHOT_DT', SNAPSHOT_DT
            )),
            256
        ) AS NORMALIZED_ROW_HASH
    FROM NORMALIZED N
),
DUPLICATE_PROFILE AS (
    SELECT
        SRC_FILE_NM,
        ITEM_ID,
        COUNT(*) AS ITEM_ID_ROW_COUNT,
        COUNT(DISTINCT NORMALIZED_ROW_HASH) AS DISTINCT_PAYLOAD_COUNT
    FROM HASHED
    WHERE ITEM_ID IS NOT NULL
    GROUP BY SRC_FILE_NM, ITEM_ID
),
RANKED AS (
    SELECT
        H.*,
        P.ITEM_ID_ROW_COUNT,
        P.DISTINCT_PAYLOAD_COUNT,
        ROW_NUMBER() OVER (
            PARTITION BY H.SRC_FILE_NM, H.ITEM_ID, H.NORMALIZED_ROW_HASH
            ORDER BY H.ROW_NUM
        ) AS EXACT_DUPLICATE_RN
    FROM HASHED H
    LEFT JOIN DUPLICATE_PROFILE P
        ON H.SRC_FILE_NM = P.SRC_FILE_NM
       AND H.ITEM_ID = P.ITEM_ID
)
SELECT
    R.*,
    COALESCE(
        ITEM_ID_ROW_COUNT > 1 AND DISTINCT_PAYLOAD_COUNT > 1,
        FALSE
    ) AS CONFLICTING_DUPLICATE_FLG,
    NULLIF(
        ARRAY_TO_STRING(
            ARRAY_CONSTRUCT_COMPACT(
                IFF(ITEM_ID IS NULL, 'MISSING_ITEM_ID', NULL),
                IFF(SUBCATEGORY_ID IS NULL, 'MISSING_SUBCATEGORY_ID', NULL),
                IFF(CATEGORY_ID IS NULL, 'MISSING_CATEGORY_ID', NULL),
                IFF(BRAND_ID IS NULL, 'MISSING_BRAND_ID', NULL),
                IFF(SNAPSHOT_DT IS NULL, 'INVALID_SNAPSHOT_DATE_IN_FILENAME', NULL),
                IFF(ACTIVE_FLG IS NULL, 'INVALID_ACTIVE_FLG', NULL),
                IFF(
                    COALESCE(ITEM_ID_ROW_COUNT > 1 AND DISTINCT_PAYLOAD_COUNT > 1, FALSE),
                    'CONFLICTING_DUPLICATE_ITEM_ID_IN_FILE',
                    NULL
                )
            ),
            '; '
        ),
        ''
    ) AS REJECT_REASON,
    CASE
        WHEN ITEM_ID IS NULL THEN 'MISSING_ITEM_ID'
        WHEN SUBCATEGORY_ID IS NULL THEN 'MISSING_SUBCATEGORY_ID'
        WHEN CATEGORY_ID IS NULL THEN 'MISSING_CATEGORY_ID'
        WHEN BRAND_ID IS NULL THEN 'MISSING_BRAND_ID'
        WHEN SNAPSHOT_DT IS NULL THEN 'INVALID_SNAPSHOT_DATE'
        WHEN ACTIVE_FLG IS NULL THEN 'INVALID_ACTIVE_FLG'
        WHEN COALESCE(ITEM_ID_ROW_COUNT > 1 AND DISTINCT_PAYLOAD_COUNT > 1, FALSE)
            THEN 'CONFLICTING_DUPLICATE_ITEM_ID'
        ELSE NULL
    END AS REJECT_CODE
FROM RANKED R;


MERGE INTO RETAIL_DB.TMP.REJ_ITEM_MASTER T
USING (
    SELECT *
    FROM TMP_ITEM_MASTER_WORK
    WHERE REJECT_REASON IS NOT NULL
) S
    ON T.SRC_FILE_NM = S.SRC_FILE_NM
   AND T.ROW_NUM = S.ROW_NUM
   AND T.QUALITY_GATE = 'GATE_1_BRONZE_TO_SILVER'
WHEN MATCHED THEN UPDATE SET
    T.ITEM_ID = S.RAW_ITEM_ID,
    T.ITEM_NAME = S.RAW_ITEM_NAME,
    T.SUBCATEGORY_ID = S.RAW_SUBCATEGORY_ID,
    T.SUBCATEGORY_NAME = S.RAW_SUBCATEGORY_NAME,
    T.CATEGORY_ID = S.RAW_CATEGORY_ID,
    T.CATEGORY_NAME = S.RAW_CATEGORY_NAME,
    T.BRAND_ID = S.RAW_BRAND_ID,
    T.BRAND_NAME = S.RAW_BRAND_NAME,
    T.UNIT_OF_MEASURE = S.RAW_UNIT_OF_MEASURE,
    T.ACTIVE_FLG = S.RAW_ACTIVE_FLG,
    T.SOURCE_INGEST_TS = S.SOURCE_INGEST_TS,
    T.BATCH_ID = S.BATCH_ID,
    T.SRC_ROW_HASH = S.SRC_ROW_HASH,
    T.REJECT_CODE = S.REJECT_CODE,
    T.REJECT_REASON = S.REJECT_REASON,
    T.AIRFLOW_RUN_ID = S.BATCH_ID,
    T.REJECTED_TS = CURRENT_TIMESTAMP(),
    T.RESOLVED_FLG = FALSE,
    T.RESOLVED_TS = NULL
WHEN NOT MATCHED THEN INSERT (
    ITEM_ID,
    ITEM_NAME,
    SUBCATEGORY_ID,
    SUBCATEGORY_NAME,
    CATEGORY_ID,
    CATEGORY_NAME,
    BRAND_ID,
    BRAND_NAME,
    UNIT_OF_MEASURE,
    ACTIVE_FLG,
    SRC_FILE_NM,
    ROW_NUM,
    SOURCE_INGEST_TS,
    BATCH_ID,
    SRC_ROW_HASH,
    QUALITY_GATE,
    REJECT_CODE,
    REJECT_REASON,
    REJECTION_ID,
    AIRFLOW_RUN_ID,
    REJECTED_TS,
    RESOLVED_FLG
)
VALUES (
    S.RAW_ITEM_ID,
    S.RAW_ITEM_NAME,
    S.RAW_SUBCATEGORY_ID,
    S.RAW_SUBCATEGORY_NAME,
    S.RAW_CATEGORY_ID,
    S.RAW_CATEGORY_NAME,
    S.RAW_BRAND_ID,
    S.RAW_BRAND_NAME,
    S.RAW_UNIT_OF_MEASURE,
    S.RAW_ACTIVE_FLG,
    S.SRC_FILE_NM,
    S.ROW_NUM,
    S.SOURCE_INGEST_TS,
    S.BATCH_ID,
    S.SRC_ROW_HASH,
    'GATE_1_BRONZE_TO_SILVER',
    S.REJECT_CODE,
    S.REJECT_REASON,
    UUID_STRING(),
    S.BATCH_ID,
    CURRENT_TIMESTAMP(),
    FALSE
);


UPDATE RETAIL_DB.TMP.REJ_ITEM_MASTER T
SET
    RESOLVED_FLG = TRUE,
    RESOLVED_TS = COALESCE(T.RESOLVED_TS, CURRENT_TIMESTAMP())
FROM TMP_ITEM_MASTER_WORK S
WHERE T.SRC_FILE_NM = S.SRC_FILE_NM
  AND T.ROW_NUM = S.ROW_NUM
  AND T.QUALITY_GATE = 'GATE_1_BRONZE_TO_SILVER'
  AND S.REJECT_REASON IS NULL;


DELETE FROM RETAIL_DB.TMP.SILVER_ITEM_MASTER T
USING TMP_ITEM_MASTER_WORK S
WHERE T.SRC_FILE_NM = S.SRC_FILE_NM
  AND T.ROW_NUM = S.ROW_NUM
  AND (
      S.REJECT_REASON IS NOT NULL
      OR S.EXACT_DUPLICATE_RN > 1
  );


MERGE INTO RETAIL_DB.TMP.SILVER_ITEM_MASTER T
USING (
    SELECT *
    FROM TMP_ITEM_MASTER_WORK
    WHERE REJECT_REASON IS NULL
      AND EXACT_DUPLICATE_RN = 1
) S
    ON T.SRC_FILE_NM = S.SRC_FILE_NM
   AND T.ROW_NUM = S.ROW_NUM
WHEN MATCHED AND T.SRC_ROW_HASH <> S.SRC_ROW_HASH THEN UPDATE SET
    T.ITEM_ID = S.ITEM_ID,
    T.ITEM_NAME = S.ITEM_NAME,
    T.SUBCATEGORY_ID = S.SUBCATEGORY_ID,
    T.SUBCATEGORY_NAME = S.SUBCATEGORY_NAME,
    T.CATEGORY_ID = S.CATEGORY_ID,
    T.CATEGORY_NAME = S.CATEGORY_NAME,
    T.BRAND_ID = S.BRAND_ID,
    T.BRAND_NAME = S.BRAND_NAME,
    T.UNIT_OF_MEASURE = S.UNIT_OF_MEASURE,
    T.ACTIVE_FLG = S.ACTIVE_FLG,
    T.SNAPSHOT_DT = S.SNAPSHOT_DT,
    T.SRC_ROW_HASH = S.SRC_ROW_HASH,
    T.BATCH_ID = S.BATCH_ID,
    T.UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    ITEM_ID,
    ITEM_NAME,
    SUBCATEGORY_ID,
    SUBCATEGORY_NAME,
    CATEGORY_ID,
    CATEGORY_NAME,
    BRAND_ID,
    BRAND_NAME,
    UNIT_OF_MEASURE,
    ACTIVE_FLG,
    SNAPSHOT_DT,
    SRC_FILE_NM,
    ROW_NUM,
    SRC_ROW_HASH,
    SRC_SYS_C,
    BATCH_ID,
    INSERT_TS,
    UPDATE_TS
)
VALUES (
    S.ITEM_ID,
    S.ITEM_NAME,
    S.SUBCATEGORY_ID,
    S.SUBCATEGORY_NAME,
    S.CATEGORY_ID,
    S.CATEGORY_NAME,
    S.BRAND_ID,
    S.BRAND_NAME,
    S.UNIT_OF_MEASURE,
    S.ACTIVE_FLG,
    S.SNAPSHOT_DT,
    S.SRC_FILE_NM,
    S.ROW_NUM,
    S.SRC_ROW_HASH,
    'RETAIL_CSV',
    S.BATCH_ID,
    CURRENT_TIMESTAMP(),
    CURRENT_TIMESTAMP()
);


MERGE INTO RETAIL_DB.TMP.SILVER_LOAD_CONTROL T
USING (
    SELECT
        'STG_ITEM_MASTER' AS SOURCE_TABLE,
        'SILVER_ITEM_MASTER' AS TARGET_TABLE,
        SRC_FILE_NM,
        MAX(BATCH_ID) AS BATCH_ID,
        COUNT(*) AS ROWS_READ,
        COUNT_IF(REJECT_REASON IS NULL AND EXACT_DUPLICATE_RN = 1) AS ROWS_LOADED,
        COUNT_IF(REJECT_REASON IS NOT NULL) AS ROWS_QUARANTINED
    FROM TMP_ITEM_MASTER_WORK
    GROUP BY SRC_FILE_NM
) S
    ON T.SOURCE_TABLE = S.SOURCE_TABLE
   AND T.TARGET_TABLE = S.TARGET_TABLE
   AND T.SRC_FILE_NM = S.SRC_FILE_NM
WHEN MATCHED THEN UPDATE SET
    T.BATCH_ID = S.BATCH_ID,
    T.AIRFLOW_RUN_ID = S.BATCH_ID,
    T.LOAD_STATUS = 'SUCCESS',
    T.COMPLETED_TS = CURRENT_TIMESTAMP(),
    T.ROWS_READ = S.ROWS_READ,
    T.ROWS_LOADED = S.ROWS_LOADED,
    T.ROWS_QUARANTINED = S.ROWS_QUARANTINED,
    T.ERROR_MESSAGE = NULL
WHEN NOT MATCHED THEN INSERT (
    CONTROL_ID,
    SOURCE_TABLE,
    TARGET_TABLE,
    SRC_FILE_NM,
    BATCH_ID,
    AIRFLOW_RUN_ID,
    LOAD_STATUS,
    STARTED_TS,
    COMPLETED_TS,
    ROWS_READ,
    ROWS_LOADED,
    ROWS_QUARANTINED,
    ERROR_MESSAGE
)
VALUES (
    UUID_STRING(),
    S.SOURCE_TABLE,
    S.TARGET_TABLE,
    S.SRC_FILE_NM,
    S.BATCH_ID,
    S.BATCH_ID,
    'SUCCESS',
    CURRENT_TIMESTAMP(),
    CURRENT_TIMESTAMP(),
    S.ROWS_READ,
    S.ROWS_LOADED,
    S.ROWS_QUARANTINED,
    NULL
);


SELECT
    SRC_FILE_NM,
    SNAPSHOT_DT,
    COUNT(*) AS ROW_COUNT,
    COUNT(DISTINCT ITEM_ID) AS DISTINCT_ITEM_COUNT
FROM RETAIL_DB.TMP.SILVER_ITEM_MASTER
GROUP BY SRC_FILE_NM, SNAPSHOT_DT
ORDER BY SNAPSHOT_DT;

SELECT
    QUALITY_GATE,
    REJECT_CODE,
    COUNT(*) AS REJECTED_ROWS
FROM RETAIL_DB.TMP.REJ_ITEM_MASTER
GROUP BY QUALITY_GATE, REJECT_CODE
ORDER BY QUALITY_GATE, REJECT_CODE;

SELECT
    ITEM_ID,
    BRAND_NAME,
    SNAPSHOT_DT,
    SRC_FILE_NM
FROM RETAIL_DB.TMP.SILVER_ITEM_MASTER
WHERE ITEM_ID = 'I006'
ORDER BY SNAPSHOT_DT;

SELECT
    SOURCE_TABLE,
    TARGET_TABLE,
    SRC_FILE_NM,
    LOAD_STATUS,
    ROWS_READ,
    ROWS_LOADED,
    ROWS_QUARANTINED
FROM RETAIL_DB.TMP.SILVER_LOAD_CONTROL
WHERE SOURCE_TABLE = 'STG_ITEM_MASTER'
  AND TARGET_TABLE = 'SILVER_ITEM_MASTER'
ORDER BY SRC_FILE_NM;

-- End of item master Bronze -> Silver transformation.
