
USE DATABASE RETAIL_DB;
USE SCHEMA TMP;
use warehouse RETAIL_WH;

-- 1. Type, normalize, hash, and classify Bronze rows.
CREATE OR REPLACE TEMP TABLE TMP_PRICE_SNAPSHOT_CLASSIFIED AS
WITH BASE AS (
    SELECT
        BUSINESS_DATE,
        ITEM_ID,
        STORE_ID,
        SELLING_PRICE_AMT,
        UNIT_COST_AMT,
        SRC_FILE_NM,
        ROW_NUM,
        INGEST_TS,
        BATCH_ID,

        NULLIF(TRIM(BUSINESS_DATE), '') AS BUSINESS_DATE_CLEAN,
        NULLIF(TRIM(ITEM_ID), '') AS ITEM_ID_CLEAN,
        NULLIF(TRIM(STORE_ID), '') AS STORE_ID_CLEAN,
        NULLIF(TRIM(SELLING_PRICE_AMT), '') AS SELLING_PRICE_AMT_CLEAN,
        NULLIF(TRIM(UNIT_COST_AMT), '') AS UNIT_COST_AMT_CLEAN
    FROM RETAIL_DB.STG.STG_PRICE_SNAPSHOT
),
TYPED AS (
    SELECT
        *,
        TRY_TO_DATE(BUSINESS_DATE_CLEAN, 'YYYY-MM-DD') AS BUSINESS_DATE_TYPED,
        TRY_TO_DECIMAL(SELLING_PRICE_AMT_CLEAN, 18, 2) AS SELLING_PRICE_AMT_TYPED,
        TRY_TO_DECIMAL(UNIT_COST_AMT_CLEAN, 18, 2) AS UNIT_COST_AMT_TYPED,

        SHA2(
            CONCAT_WS('|',
                COALESCE(BUSINESS_DATE, '<NULL>'),
                COALESCE(ITEM_ID, '<NULL>'),
                COALESCE(STORE_ID, '<NULL>'),
                COALESCE(SELLING_PRICE_AMT, '<NULL>'),
                COALESCE(UNIT_COST_AMT, '<NULL>')
            ),
            256
        ) AS SRC_ROW_HASH
    FROM BASE
),
VALIDATED AS (
    SELECT
        *,
        CASE
            WHEN BUSINESS_DATE_CLEAN IS NULL THEN 'MISSING_BUSINESS_DATE'
            WHEN BUSINESS_DATE_TYPED IS NULL THEN 'INVALID_BUSINESS_DATE'
            WHEN ITEM_ID_CLEAN IS NULL THEN 'MISSING_ITEM_ID'
            WHEN STORE_ID_CLEAN IS NULL THEN 'MISSING_STORE_ID'
            WHEN SELLING_PRICE_AMT_CLEAN IS NOT NULL
                 AND SELLING_PRICE_AMT_TYPED IS NULL
                THEN 'INVALID_SELLING_PRICE_AMT'
            WHEN UNIT_COST_AMT_CLEAN IS NOT NULL
                 AND UNIT_COST_AMT_TYPED IS NULL
                THEN 'INVALID_UNIT_COST_AMT'
            ELSE NULL
        END AS BASE_REJECT_CODE,

        CASE
            WHEN BUSINESS_DATE_CLEAN IS NULL
                THEN 'BUSINESS_DATE is missing or blank.'
            WHEN BUSINESS_DATE_TYPED IS NULL
                THEN 'BUSINESS_DATE could not be converted using YYYY-MM-DD.'
            WHEN ITEM_ID_CLEAN IS NULL
                THEN 'ITEM_ID is missing or blank.'
            WHEN STORE_ID_CLEAN IS NULL
                THEN 'STORE_ID is missing or blank.'
            WHEN SELLING_PRICE_AMT_CLEAN IS NOT NULL
                 AND SELLING_PRICE_AMT_TYPED IS NULL
                THEN 'SELLING_PRICE_AMT is not a valid NUMBER(18,2) value.'
            WHEN UNIT_COST_AMT_CLEAN IS NOT NULL
                 AND UNIT_COST_AMT_TYPED IS NULL
                THEN 'UNIT_COST_AMT is not a valid NUMBER(18,2) value.'
            ELSE NULL
        END AS BASE_REJECT_REASON
    FROM TYPED
),
VALID_ROWS AS (
    SELECT
        *,
        SHA2(
            CONCAT_WS('|',
                TO_VARCHAR(BUSINESS_DATE_TYPED, 'YYYY-MM-DD'),
                ITEM_ID_CLEAN,
                STORE_ID_CLEAN,
                COALESCE(TO_VARCHAR(SELLING_PRICE_AMT_TYPED), '<NULL>'),
                COALESCE(TO_VARCHAR(UNIT_COST_AMT_TYPED), '<NULL>')
            ),
            256
        ) AS PAYLOAD_HASH
    FROM VALIDATED
    WHERE BASE_REJECT_CODE IS NULL
),
KEY_STATS AS (
    SELECT
        BUSINESS_DATE_TYPED,
        ITEM_ID_CLEAN,
        STORE_ID_CLEAN,
        COUNT(*) AS KEY_ROW_COUNT,
        COUNT(DISTINCT PAYLOAD_HASH) AS PAYLOAD_VARIANT_COUNT
    FROM VALID_ROWS
    GROUP BY
        BUSINESS_DATE_TYPED,
        ITEM_ID_CLEAN,
        STORE_ID_CLEAN
),
RANKED_VALID_ROWS AS (
    SELECT
        *,
        ROW_NUMBER() OVER (
            PARTITION BY
                BUSINESS_DATE_TYPED,
                ITEM_ID_CLEAN,
                STORE_ID_CLEAN,
                PAYLOAD_HASH
            ORDER BY SRC_FILE_NM, ROW_NUM
        ) AS EXACT_DUPLICATE_RN
    FROM VALID_ROWS
)
SELECT
    V.*,
    COALESCE(K.KEY_ROW_COUNT, 0) AS KEY_ROW_COUNT,
    COALESCE(K.PAYLOAD_VARIANT_COUNT, 0) AS PAYLOAD_VARIANT_COUNT,
    R.EXACT_DUPLICATE_RN,

    CASE
        WHEN V.BASE_REJECT_CODE IS NOT NULL
            THEN V.BASE_REJECT_CODE
        WHEN K.PAYLOAD_VARIANT_COUNT > 1
            THEN 'CONFLICTING_DUPLICATE_BUSINESS_KEY'
        WHEN R.EXACT_DUPLICATE_RN > 1
            THEN 'DUPLICATE_BUSINESS_KEY'
        ELSE NULL
    END AS REJECT_CODE,

    CASE
        WHEN V.BASE_REJECT_CODE IS NOT NULL
            THEN V.BASE_REJECT_REASON
        WHEN K.PAYLOAD_VARIANT_COUNT > 1
            THEN 'Different price values exist for the same BUSINESS_DATE, ITEM_ID and STORE_ID. All rows for this business key are quarantined.'
        WHEN R.EXACT_DUPLICATE_RN > 1
            THEN 'An identical record exists for the same business key. The first row, ordered by source file and row number, is retained.'
        ELSE NULL
    END AS REJECT_REASON
FROM VALIDATED V
LEFT JOIN KEY_STATS K
    ON V.BUSINESS_DATE_TYPED = K.BUSINESS_DATE_TYPED
   AND V.ITEM_ID_CLEAN = K.ITEM_ID_CLEAN
   AND V.STORE_ID_CLEAN = K.STORE_ID_CLEAN
LEFT JOIN RANKED_VALID_ROWS R
    ON V.SRC_FILE_NM = R.SRC_FILE_NM
   AND V.ROW_NUM = R.ROW_NUM;


-- 2. Remove stale Gate 1 rejection records for source rows that now pass.
DELETE FROM RETAIL_DB.TMP.REJ_PRICE_SNAPSHOT T
USING TMP_PRICE_SNAPSHOT_CLASSIFIED S
WHERE T.SRC_FILE_NM = S.SRC_FILE_NM
  AND T.ROW_NUM = S.ROW_NUM
  AND T.QUALITY_GATE = 'GATE_1_BRONZE_TO_SILVER'
  AND S.REJECT_CODE IS NULL;


-- 3. Upsert current Gate 1 rejections.
MERGE INTO RETAIL_DB.TMP.REJ_PRICE_SNAPSHOT T
USING (
    SELECT
        BUSINESS_DATE,
        ITEM_ID,
        STORE_ID,
        SELLING_PRICE_AMT,
        UNIT_COST_AMT,
        SRC_FILE_NM,
        ROW_NUM,
        INGEST_TS AS SOURCE_INGEST_TS,
        BATCH_ID,
        SRC_ROW_HASH,
        REJECT_CODE,
        REJECT_REASON
    FROM TMP_PRICE_SNAPSHOT_CLASSIFIED
    WHERE REJECT_CODE IS NOT NULL
) S
ON T.SRC_FILE_NM = S.SRC_FILE_NM
AND T.ROW_NUM = S.ROW_NUM
AND T.QUALITY_GATE = 'GATE_1_BRONZE_TO_SILVER'
WHEN MATCHED THEN UPDATE SET
    T.BUSINESS_DATE = S.BUSINESS_DATE,
    T.ITEM_ID = S.ITEM_ID,
    T.STORE_ID = S.STORE_ID,
    T.SELLING_PRICE_AMT = S.SELLING_PRICE_AMT,
    T.UNIT_COST_AMT = S.UNIT_COST_AMT,
    T.SOURCE_INGEST_TS = S.SOURCE_INGEST_TS,
    T.BATCH_ID = S.BATCH_ID,
    T.SRC_ROW_HASH = S.SRC_ROW_HASH,
    T.REJECT_CODE = S.REJECT_CODE,
    T.REJECT_REASON = S.REJECT_REASON,
    T.REJECTED_TS = CURRENT_TIMESTAMP(),
    T.RESOLVED_FLG = FALSE,
    T.RESOLVED_TS = NULL
WHEN NOT MATCHED THEN INSERT (
    BUSINESS_DATE,
    ITEM_ID,
    STORE_ID,
    SELLING_PRICE_AMT,
    UNIT_COST_AMT,
    SRC_FILE_NM,
    ROW_NUM,
    SOURCE_INGEST_TS,
    BATCH_ID,
    SRC_ROW_HASH,
    QUALITY_GATE,
    REJECT_CODE,
    REJECT_REASON,
    REJECTION_ID,
    AIRFLOW_RUN_ID,
    REJECTED_TS,
    RESOLVED_FLG,
    RESOLVED_TS
) VALUES (
    S.BUSINESS_DATE,
    S.ITEM_ID,
    S.STORE_ID,
    S.SELLING_PRICE_AMT,
    S.UNIT_COST_AMT,
    S.SRC_FILE_NM,
    S.ROW_NUM,
    S.SOURCE_INGEST_TS,
    S.BATCH_ID,
    S.SRC_ROW_HASH,
    'GATE_1_BRONZE_TO_SILVER',
    S.REJECT_CODE,
    S.REJECT_REASON,
    UUID_STRING(),
    NULL,
    CURRENT_TIMESTAMP(),
    FALSE,
    NULL
);


-- 4. Remove previously loaded Silver price rows for keys that are now
--    known to contain conflicting source payloads.
DELETE FROM RETAIL_DB.TMP.SILVER_PRICE_SNAPSHOT T
USING (
    SELECT DISTINCT
        BUSINESS_DATE_TYPED AS BUSINESS_DATE,
        ITEM_ID_CLEAN AS ITEM_ID,
        STORE_ID_CLEAN AS STORE_ID
    FROM TMP_PRICE_SNAPSHOT_CLASSIFIED
    WHERE REJECT_CODE = 'CONFLICTING_DUPLICATE_BUSINESS_KEY'
) S
WHERE T.BUSINESS_DATE = S.BUSINESS_DATE
  AND T.ITEM_ID = S.ITEM_ID
  AND T.STORE_ID = S.STORE_ID;


-- 5. Merge only valid, non-duplicate rows into Silver.
MERGE INTO RETAIL_DB.TMP.SILVER_PRICE_SNAPSHOT T
USING (
    SELECT
        BUSINESS_DATE_TYPED AS BUSINESS_DATE,
        ITEM_ID_CLEAN AS ITEM_ID,
        STORE_ID_CLEAN AS STORE_ID,
        SELLING_PRICE_AMT_TYPED AS SELLING_PRICE_AMT,
        UNIT_COST_AMT_TYPED AS UNIT_COST_AMT,
        SRC_FILE_NM,
        ROW_NUM,
        SRC_ROW_HASH,
        BATCH_ID
    FROM TMP_PRICE_SNAPSHOT_CLASSIFIED
    WHERE REJECT_CODE IS NULL
) S
ON T.BUSINESS_DATE = S.BUSINESS_DATE
AND T.ITEM_ID = S.ITEM_ID
AND T.STORE_ID = S.STORE_ID
WHEN MATCHED THEN UPDATE SET
    T.SELLING_PRICE_AMT = S.SELLING_PRICE_AMT,
    T.UNIT_COST_AMT = S.UNIT_COST_AMT,
    T.SRC_FILE_NM = S.SRC_FILE_NM,
    T.ROW_NUM = S.ROW_NUM,
    T.SRC_ROW_HASH = S.SRC_ROW_HASH,
    T.SRC_SYS_C = 'RETAIL_CSV',
    T.BATCH_ID = S.BATCH_ID,
    T.UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    BUSINESS_DATE,
    ITEM_ID,
    STORE_ID,
    SELLING_PRICE_AMT,
    UNIT_COST_AMT,
    SRC_FILE_NM,
    ROW_NUM,
    SRC_ROW_HASH,
    SRC_SYS_C,
    BATCH_ID
) VALUES (
    S.BUSINESS_DATE,
    S.ITEM_ID,
    S.STORE_ID,
    S.SELLING_PRICE_AMT,
    S.UNIT_COST_AMT,
    S.SRC_FILE_NM,
    S.ROW_NUM,
    S.SRC_ROW_HASH,
    'RETAIL_CSV',
    S.BATCH_ID
);


-- 6. Record per-file processing counts in Silver load control.
MERGE INTO RETAIL_DB.TMP.SILVER_LOAD_CONTROL T
USING (
    SELECT
        'STG_PRICE_SNAPSHOT' AS SOURCE_TABLE,
        'SILVER_PRICE_SNAPSHOT' AS TARGET_TABLE,
        SRC_FILE_NM,
        MAX(BATCH_ID) AS BATCH_ID,
        COUNT(*) AS ROWS_READ,
        SUM(IFF(REJECT_CODE IS NULL, 1, 0)) AS ROWS_LOADED,
        SUM(IFF(REJECT_CODE IS NOT NULL, 1, 0)) AS ROWS_QUARANTINED
    FROM TMP_PRICE_SNAPSHOT_CLASSIFIED
    GROUP BY SRC_FILE_NM
) S
ON T.SOURCE_TABLE = S.SOURCE_TABLE
AND T.TARGET_TABLE = S.TARGET_TABLE
AND T.SRC_FILE_NM = S.SRC_FILE_NM
WHEN MATCHED THEN UPDATE SET
    T.BATCH_ID = S.BATCH_ID,
    T.LOAD_STATUS = 'SUCCESS',
    T.STARTED_TS = CURRENT_TIMESTAMP(),
    T.COMPLETED_TS = CURRENT_TIMESTAMP(),
    T.ROWS_READ = S.ROWS_READ,
    T.ROWS_LOADED = S.ROWS_LOADED,
    T.ROWS_QUARANTINED = S.ROWS_QUARANTINED,
    T.ERROR_MESSAGE = NULL
WHEN NOT MATCHED THEN INSERT (
    CONTROL_ID,
    SOURCE_TABLE,
    TARGET_TABLE,
    SRC_FILE_NM,
    SRC_FILE_SIZE_BYTES,
    SRC_FILE_CHECKSUM,
    BATCH_ID,
    AIRFLOW_RUN_ID,
    LOAD_STATUS,
    STARTED_TS,
    COMPLETED_TS,
    ROWS_READ,
    ROWS_LOADED,
    ROWS_QUARANTINED,
    ERROR_MESSAGE
) VALUES (
    UUID_STRING(),
    S.SOURCE_TABLE,
    S.TARGET_TABLE,
    S.SRC_FILE_NM,
    NULL,
    NULL,
    S.BATCH_ID,
    NULL,
    'SUCCESS',
    CURRENT_TIMESTAMP(),
    CURRENT_TIMESTAMP(),
    S.ROWS_READ,
    S.ROWS_LOADED,
    S.ROWS_QUARANTINED,
    NULL
);


-- 7. Optional immediate summary for this manual run.
SELECT
    SRC_FILE_NM,
    COUNT(*) AS ROWS_READ,
    SUM(IFF(REJECT_CODE IS NULL, 1, 0)) AS ROWS_LOADED,
    SUM(IFF(REJECT_CODE IS NOT NULL, 1, 0)) AS ROWS_QUARANTINED
FROM TMP_PRICE_SNAPSHOT_CLASSIFIED
GROUP BY SRC_FILE_NM
ORDER BY SRC_FILE_NM;
